#!/usr/bin/env python3
"""E14 of docs/reports/NAV_ITEM_LISTS.md (sub:nav.examine): one-finger touch rotate and two-finger pinch zoom of the EXAMINE viewer.

  python3 -I -B oracle/tools/gen_rea_b24_touch.py

Writes the synthetic world oracle/synthetic-rea-b24-nav/touch-examine.wrl, the scripts oracle/synthetic-rea-b24-nav/scripts/touch-*.json and
oracle/synthetic-rea-b24-nav/cases-touch.txt (`name world script msaa`). New files only. The touch events are
{ "type": "touchstart" | "touchmove", "points": [[x, y], ...] } (every touch that is down after the event, the index is the
touch's id) and { "type": "touchend", "ids": [id, ...] } (those touches are released; no "ids": all), pixels with the origin at
the bottom left like the mouse events. The recorder
(oracle/x_ite-anim.mjs) sends them as DevTools `Input.dispatchTouchEvent`; `x3d-drive` feeds the viewer the same events.
All touch coordinates are whole pixels. Clean-room: the world is a few boxes, written for this test.
"""
import json, os

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
d = os.path.join(root, "oracle", "synthetic-rea-b24-nav")
DT = 1 / 30

WORLD = """#VRML V2.0 utf8
# E14 touch navigation world (generated by oracle/tools/gen_rea_b24_touch.py). Synthetic, clean-room.
NavigationInfo { type [ "EXAMINE" ] }
Viewpoint { position 0 0 12 description "touch front" }
Transform { translation 2 1 0 children Shape { appearance Appearance { material Material { diffuseColor 0.9 0.9 0.2 } } geometry Box { size 1.5 1.5 1.5 } } }
Transform { translation -3 0 -2 children Shape { appearance Appearance { material Material { diffuseColor 0.2 0.9 0.9 } } geometry Box { size 1 3 1 } } }
Transform { translation 0 -2 0 children Shape { appearance Appearance { material Material { diffuseColor 0.5 0.5 0.5 } } geometry Box { size 12 0.2 8 } } }
"""


class S:
    def __init__(self, frames, capture):
        self.ev, self.frames, self.capture = [], frames, capture

    def add(self, frame, kind, *points, ids=None):
        e = {"frame": frame, "type": kind}
        if kind != "touchend":
            e["points"] = [list(p) for p in points]
        elif ids is not None:
            e["ids"] = ids
        self.ev.append(e)

    def json(self):
        return {"size": [512, 512], "t0": 946684800, "dt": DT, "capture": self.capture, "dump": [], "frames": self.frames, "events": self.ev}


def rotate(s, f0, step, n, release_same_frame):
    """One finger down at the center at f0, n moves (one per frame), then the release (same frame as the last move, or one later)."""
    x, y = 256, 256
    s.add(f0, "touchstart", (x, y))
    for i in range(1, n + 1):
        s.add(f0 + i, "touchmove", (x + step[0] * i, y + step[1] * i))
    last = f0 + n
    s.add(last if release_same_frame else last + 1, "touchend")
    return last + 1


def pinch(s, f0, half0, per_frame, n, tilt=0):
    """Two fingers down on a horizontal line around (256, 256), half0 pixels from the center, then n moves that change each finger's
    distance from the center by per_frame pixels (negative: together), then both released (the second finger first)."""
    a, b = (256 - half0, 256), (256 + half0, 256)
    s.add(f0, "touchstart", a)
    s.add(f0, "touchstart", a, b)
    for i in range(1, n + 1):
        h = half0 + per_frame * i
        s.add(f0 + i, "touchmove", (256 - h, 256 + tilt * i), (256 + h, 256 - tilt * i))
    last = f0 + n
    h = half0 + per_frame * n
    s.add(last + 1, "touchend", ids=[0])
    s.add(last + 1, "touchend")
    return last + 2


cases = {}

s = S(60, [20, 40, 60])
rotate(s, 2, (8, 5), 12, False)
cases["touch-rotate"] = s

s = S(110, [16, 40, 110])
rotate(s, 2, (14, 9), 12, True)
cases["touch-rotate-spin"] = s

s = S(70, [8, 14, 30, 70])
pinch(s, 2, 120, -8, 10)
cases["touch-pinch-in"] = s

s = S(70, [8, 14, 30, 70])
pinch(s, 2, 40, 8, 10)
cases["touch-pinch-out"] = s

s = S(110, [16, 30, 45, 70, 110])
nxt = rotate(s, 2, (8, 5), 12, False)
pinch(s, nxt + 10, 100, -7, 10)
cases["touch-rotate-then-pinch"] = s

# A second finger added during a one-finger rotate: touchstart with two touches ends the rotate and starts the pinch.
s = S(80, [8, 12, 30, 80])
s.add(2, "touchstart", (200, 256))
for i in range(1, 6):
    s.add(2 + i, "touchmove", (200 + 8 * i, 256 + 5 * i))
s.add(9, "touchstart", (240, 281), (340, 281))
for i in range(1, 9):
    s.add(9 + i, "touchmove", (240 + 8 * i, 281), (340 - 8 * i, 281))
s.add(19, "touchend", ids=[0])
s.add(19, "touchend")
cases["touch-add-finger-pinch"] = s

# Pinch zoom with the fingers on a slanted line (opposed, not on the horizontal), in then out in one gesture.
s = S(70, [12, 30, 70])
s.add(2, "touchstart", (206, 226))
s.add(2, "touchstart", (206, 226), (306, 286))
for i in range(1, 7):
    s.add(2 + i, "touchmove", (206 + 8 * i, 226 + 5 * i), (306 - 8 * i, 286 - 5 * i))
s.add(10, "touchend", ids=[0])
s.add(10, "touchend")
cases["touch-pinch-slanted"] = s

os.makedirs(os.path.join(d, "scripts"), exist_ok=True)
open(os.path.join(d, "touch-examine.wrl"), "w").write(WORLD)
lines = []
for name, sc in cases.items():
    json.dump(sc.json(), open(os.path.join(d, "scripts", name + ".json"), "w"), indent=1)
    lines.append(f"{name} oracle/synthetic-rea-b24-nav/touch-examine.wrl oracle/synthetic-rea-b24-nav/scripts/{name}.json 0")
open(os.path.join(d, "cases-touch.txt"), "w").write("\n".join(lines) + "\n")
print(len(cases), "cases")
