def write_tone(path):
    import math, wave
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(1)
        w.setframerate(8000)
        w.writeframes(bytes(int(128 + 100 * math.sin(2 * math.pi * 440 * i / 8000)) for i in range(2000)))

