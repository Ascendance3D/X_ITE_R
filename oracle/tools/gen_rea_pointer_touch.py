#!/usr/bin/env python3
"""sub:pointer.picking: touch input (touchstart, touchmove, touchend, touchcancel) into the pointing device sensors.

  python3 -I -B oracle/tools/gen_rea_pointer_touch.py

Writes the synthetic world oracle/synthetic-rea-pointer-touch/pointer-touch.wrl, the scripts
oracle/synthetic-rea-pointer-touch/scripts/*.json and oracle/synthetic-rea-pointer-touch/cases.txt (`name world script msaa`). New files only.
The touch events are those of oracle/tools/gen_rea_b24_touch.py (origin bottom left, whole pixels; `touchstart` / `touchmove` with
"points", `touchend` with "ids"), plus `touchcancel` (every touch that is down is cancelled: DevTools `touchCancel`). The recorder
(oracle/x_ite-anim.mjs) sends them to Chrome; `x3d-drive` feeds the viewer the same. The world is a TouchSensor, a PlaneSensor, a
CylinderSensor, a SphereSensor and an Anchor (to a Viewpoint), each on a Box, and a Script that writes every output event of the
sensors into the string `hist` (the scene text of each dumped frame shows it). Clean-room: written for this test.
"""
import json, os

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
d = os.path.join(root, "oracle", "synthetic-rea-pointer-touch")
DT = 1 / 30

# Pixel centers (origin bottom left) of the five boxes, size 1.6 (about 99 px), the anchor 1.2.
TS, PS, CS, SS, AN = (102, 380), (410, 380), (102, 132), (410, 132), (256, 256)

LOGS = {
    "TS": ["isOver:SFBool", "isActive:SFBool", "touchTime:SFTime", "hitPoint_changed:SFVec3f", "hitNormal_changed:SFVec3f", "hitTexCoord_changed:SFVec2f"],
    "PS": ["isOver:SFBool", "isActive:SFBool", "trackPoint_changed:SFVec3f", "translation_changed:SFVec3f"],
    "CS": ["isOver:SFBool", "isActive:SFBool", "trackPoint_changed:SFVec3f", "rotation_changed:SFRotation"],
    "SS": ["isOver:SFBool", "isActive:SFBool", "trackPoint_changed:SFVec3f", "rotation_changed:SFRotation"],
}


def world():
    decl, funcs, routes = [], [], []
    for n, evs in LOGS.items():
        for e in evs:
            name, ty = e.split(":")
            f = f"{n}_{name.split('_')[0]}"
            decl.append(f"  inputOnly {ty} {f}")
            val = "(v - 946684800) .toFixed (4)" if ty == "SFTime" else "v"
            funcs.append(f"    function {f} (v) {{ hist = hist + ' {f}=' + {val}; }}")
            routes.append(f"ROUTE {n}.{name} TO LOG.{f}")
    return f"""#VRML V2.0 utf8
# Synthetic world (generated by oracle/tools/gen_rea_pointer_touch.py). Touch input into the pointing device sensors.
NavigationInfo {{ type [ "EXAMINE" ] }}
Viewpoint {{ position 0 0 10 description "front" }}
DEF V2 Viewpoint {{ position 1 1 10 orientation 0 0 1 0.2 description "anchored" }}
Transform {{ translation -2.5 2 0 children [ DEF TS TouchSensor {{ description "touch" }} Shape {{ geometry Box {{ size 1.6 1.6 1.6 }} }} ] }}
Transform {{ translation 2.5 2 0 children [ DEF PS PlaneSensor {{ minPosition -3 -3 maxPosition 3 3 }} Shape {{ geometry Box {{ size 1.6 1.6 1.6 }} }} ] }}
Transform {{ translation -2.5 -2 0 children [ DEF CS CylinderSensor {{ }} Shape {{ geometry Box {{ size 1.6 1.6 1.6 }} }} ] }}
Transform {{ translation 2.5 -2 0 children [ DEF SS SphereSensor {{ }} Shape {{ geometry Box {{ size 1.6 1.6 1.6 }} }} ] }}
Anchor {{ url "#V2" description "go" children Shape {{ geometry Box {{ size 1.2 1.2 1.2 }} }} }}
DEF LOG Script {{
  inputOutput SFString hist ""
{chr(10).join(decl)}
  url "ecmascript:
{chr(10).join(funcs)}
  "
}}
{chr(10).join(routes)}
"""


class S:
    def __init__(self, frames):
        self.ev, self.frames = [], frames

    def add(self, frame, kind, *points, ids=None):
        e = {"frame": frame, "type": kind}
        if kind in ("touchstart", "touchmove"):
            e["points"] = [list(p) for p in points]
        elif kind == "touchend" and ids is not None:
            e["ids"] = ids
        self.ev.append(e)

    def json(self):
        return {"size": [512, 512], "t0": 946684800, "dt": DT, "capture": [], "dump": list(range(1, self.frames + 1)), "frames": self.frames, "events": self.ev}


def tap(s, f, p):
    s.add(f, "touchstart", p)
    s.add(f + 2, "touchend")
    return f + 5


def drag(s, f, p, step, n):
    s.add(f, "touchstart", p)
    for i in range(1, n + 1):
        s.add(f + i, "touchmove", (p[0] + step[0] * i, p[1] + step[1] * i))
    s.add(f + n + 1, "touchend")
    return f + n + 4


cases = {}

s = S(60)
f = 2
for p in (TS, PS, CS, SS, AN, (30, 30)):
    f = tap(s, f, p)
cases["tap-each"] = s

s = S(90)
f = drag(s, 2, TS, (6, -4), 6)
f = drag(s, f, PS, (8, -6), 8)
f = drag(s, f, CS, (9, 3), 8)
f = drag(s, f, SS, (-7, 6), 8)
cases["drag-each"] = s

# A touch that moves off the sensor and back (isOver follows the touch), and a touch that starts off the sensor and moves onto it.
s = S(50)
s.add(2, "touchstart", TS)
s.add(3, "touchmove", (TS[0] + 90, TS[1]))
s.add(4, "touchmove", (TS[0] + 130, TS[1]))
s.add(5, "touchmove", (TS[0] + 10, TS[1] + 5))
s.add(6, "touchend")
s.add(10, "touchstart", (256, 440))
s.add(11, "touchmove", (PS[0], PS[1]))
s.add(12, "touchmove", (PS[0] + 20, PS[1] + 10))
s.add(13, "touchend")
cases["leave-and-enter"] = s

# A second finger during a drag: touchstart with two touches ends the first (mouseup), the second finger moves, then both are released.
s = S(70)
s.add(2, "touchstart", PS)
for i in range(1, 4):
    s.add(2 + i, "touchmove", (PS[0] + 8 * i, PS[1] - 6 * i))
s.add(7, "touchstart", (PS[0] + 24, PS[1] - 18), (SS[0], SS[1]))
for i in range(1, 4):
    s.add(7 + i, "touchmove", (PS[0] + 24, PS[1] - 18), (SS[0] + 8 * i, SS[1] + 6 * i))
s.add(12, "touchend", ids=[0])
s.add(13, "touchend")
# The same during a TouchSensor press, and a second finger down first (no sensor is pressed by a two-finger start).
s.add(20, "touchstart", TS)
s.add(22, "touchstart", TS, (CS[0], CS[1]))
s.add(24, "touchend", ids=[1])
s.add(25, "touchend")
s.add(30, "touchstart", SS)
s.add(31, "touchstart", SS, (CS[0], CS[1]))
s.add(32, "touchend", ids=[0])
s.add(33, "touchend")
cases["second-finger"] = s

# touchcancel: X_ITE has no touchcancel handler (a pressed sensor stays active until a touchend or mouseup reaches it).
s = S(50)
s.add(2, "touchstart", TS)
s.add(4, "touchmove", (TS[0] + 5, TS[1]))
s.add(6, "touchcancel")
s.add(10, "touchstart", PS)
s.add(12, "touchmove", (PS[0] + 15, PS[1] - 10))
s.add(14, "touchcancel")
s.add(18, "touchstart", (256, 440))
s.add(19, "touchmove", (PS[0] + 5, PS[1] + 5))
s.add(20, "touchend")
s.add(22, "touchstart", SS)
s.add(24, "touchend")
cases["cancel"] = s

# A tap-and-drag that starts on empty space moves the EXAMINE viewer; a sensor press stops it (the poses show it).
s = S(40)
drag(s, 2, (256, 60), (10, 6), 8)
drag(s, 16, TS, (10, 6), 8)
cases["empty-vs-sensor"] = s

os.makedirs(os.path.join(d, "scripts"), exist_ok=True)
open(os.path.join(d, "pointer-touch.wrl"), "w").write(world())
lines = []
for name, sc in cases.items():
    sc = sc.json()
    sc["capture"] = []
    json.dump(sc, open(os.path.join(d, "scripts", name + ".json"), "w"), indent=1)
    lines.append(f"{name} oracle/synthetic-rea-pointer-touch/pointer-touch.wrl oracle/synthetic-rea-pointer-touch/scripts/{name}.json 0")
open(os.path.join(d, "cases.txt"), "w").write("\n".join(lines) + "\n")
print(len(cases), "cases")
