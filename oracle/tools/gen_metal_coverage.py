#!/usr/bin/env python3
"""Metal coverage worlds (issues #69 and #89): how the pinned page's pointing buffer rasterizes 1 px lines and point sprites.

The pointing buffer of the pinned X_ITE 16.5.0 draws gl.LINES and gl.POINTS into a 1x1 target; whether a pixel centre is
covered, and which gl_PointCoord it gets, belongs to the rasterizer of the GPU and of the ANGLE backend. Every probe here
sits on a pixel centre, so a probe is a coverage sample of that pixel (script key pickProbes: hit or miss, the interpolated
hit point of a line, the texCoord of a sprite).

  ml-lines-a, ml-lines-b   one 1 px line per 64 px cell (aliased gl.LINES, no LineProperties), starting at a jittered point,
                           at many angles; probes on every pixel centre within 2.5 px of a segment
  ml-sprite-size           256 point sprites of size 3 to 5 in steps of 1/128 (PointProperties attenuation 1 0 0:
                           gl_PointSize = pointSizeScaleFactor + 1), one per 32 px cell at a jittered sub-pixel position;
                           probes on every pixel centre of the sprite's bounding box
  ml-sprite-size-wide      sprites of size 6 to 55 (steps that grow with the size), probes on the row and the column
                           through the centre
  ml-sprite-two            256 PointSet points without PointProperties (gl_PointSize 2, the page's minimum), at the positions of
                           ml-sprite-pos; probes on every pixel centre of the bounding box
  ml-sprite-low            sprites of size 2 to 3 in steps of 1/256 (PointProperties), at jittered positions
  ml-sprite-clamp          one sprite of size 600 at the centre (above ALIASED_POINT_SIZE_RANGE [1] of ANGLE on Metal, 511; the
                           NVIDIA host allows 2047), probes along the row and the column through its centre every 8 pixels
  ml-sprite-pos            256 sprites of size 4 at sub-pixel positions on a 1/1024 pixel lattice
  ml-sprite-pos-frac       the same at size 7.3

  python3 -I -B oracle/tools/gen_metal_coverage.py

writes oracle/synthetic-metal-coverage/*.wrl and *.json. Newly authored; no historical content. 512x512, Viewpoint at 0 0 10 with the default fieldOfView, pointer coordinates from the left and the bottom.
"""
import json, math, os

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "synthetic-metal-coverage"))
os.makedirs(root, exist_ok=True)
HEAD = "#X3D V4.0 utf8\nPROFILE Full\n# Metal coverage oracle world (generated by oracle/tools/gen_metal_coverage.py).\n"
VP = "Viewpoint { position 0 0 10 }\nNavigationInfo { type \"NONE\" }\nBackground { skyColor 0.1 0.1 0.15 }\n"
F = 1 / math.tan(math.pi / 8)


class Lcg:
    """Deterministic pseudo-random numbers in [0, 1)."""

    def __init__(self, seed):
        self.s = seed

    def next(self):
        self.s = (self.s * 6364136223846793005 + 1442695040888963407) % (1 << 64)
        return (self.s >> 11) / (1 << 53)


def world(size, x, y):
    """Pointer coordinates (x from the left, y from the bottom) -> the world point on the plane z = 0."""
    return [(2 * x / size - 1) * 10 / F, (2 * y / size - 1) * 10 / F, 0]


def fmt(p):
    return " ".join(f"{c:.9g}" for c in p)


def write(name, text, probes, size):
    open(os.path.join(root, name + ".wrl"), "w").write(HEAD + VP + text)
    json.dump({"size": [size, size], "t0": 946684800, "dt": 1 / 30, "settle": False, "frames": 2, "capture": [1],
               "dump": [1], "events": [], "pickProbes": probes}, open(os.path.join(root, name + ".json"), "w"))


def lines(name, seed):
    size, cell = 512, 64
    rnd = Lcg(seed)
    body, probes = "", []
    for j in range(size // cell):
        for i in range(size // cell):
            ax = i * cell + cell / 2 + (rnd.next() - 0.5) * 6
            ay = j * cell + cell / 2 + (rnd.next() - 0.5) * 6
            ang = rnd.next() * 2 * math.pi
            length = 20 + rnd.next() * 8
            bx, by = ax + length * math.cos(ang), ay + length * math.sin(ang)
            a, b = world(size, ax, ay), world(size, bx, by)
            body += ("Shape { geometry IndexedLineSet { coord Coordinate { point [ %s, %s ] } coordIndex [ 0 1 ] } }\n"
                     % (fmt(a), fmt(b)))
            dx, dy = bx - ax, by - ay
            ln = math.hypot(dx, dy)
            for py in range(int(min(ay, by)) - 3, int(max(ay, by)) + 4):
                for px in range(int(min(ax, bx)) - 3, int(max(ax, bx)) + 4):
                    cx, cy = px + 0.5, py + 0.5
                    t = ((cx - ax) * dx + (cy - ay) * dy) / ln
                    d = abs(-(cx - ax) * dy + (cy - ay) * dx) / ln
                    if d <= 2.5 and -1.5 <= t <= ln + 1.5:
                        probes.append([cx, cy])
    write(name, body, probes, size)


def sprite(s, largest=200):
    return ("Shape { appearance Appearance { pointProperties PointProperties { pointSizeScaleFactor %.9g pointSizeMinValue 1 "
            "pointSizeMaxValue " + str(largest) + " attenuation 1 0 0 } } geometry PointSet { coord Coordinate { point [ %s ] } } }\n")


def sprites(name, sizes, size, cell, positions, full_box=True):
    """One sprite of size S per cell; positions[k] = (fx, fy) the sub-pixel offset of its centre in its cell."""
    body, probes = "", []
    per_row = size // cell
    for k, (s, (fx, fy)) in enumerate(zip(sizes, positions)):
        cx = (k % per_row) * cell + cell / 2 + fx
        cy = (k // per_row) * cell + cell / 2 + fy
        body += sprite(s) % (s - 1, fmt(world(size, cx, cy)))
        x0, x1 = math.floor(cx - s / 2) - 1, math.ceil(cx + s / 2) + 1
        y0, y1 = math.floor(cy - s / 2) - 1, math.ceil(cy + s / 2) + 1
        if full_box:
            probes += [[px + 0.5, py + 0.5] for py in range(y0, y1 + 1) for px in range(x0, x1 + 1)]
        else:
            py, px = math.floor(cy), math.floor(cx)
            probes += [[q + 0.5, py + 0.5] for q in range(x0, x1 + 1)]
            probes += [[px + 0.5, q + 0.5] for q in range(y0, y1 + 1) if q != py]
    write(name, body, probes, size)


lines("ml-lines-a", 12345)
lines("ml-lines-b", 67890)

rnd = Lcg(24680)
jit = lambda: ((rnd.next() - 0.5) * 6, (rnd.next() - 0.5) * 6)
sprites("ml-sprite-size", [3 + k / 128 for k in range(256)], 512, 32, [jit() for _ in range(256)])

wide = []
s = 6.0
while s < 55:
    wide.append(s)
    s += 1 / 4 if s < 12 else 1 / 2 if s < 24 else 2
sprites("ml-sprite-size-wide", wide, 512, 64, [jit() for _ in wide], full_box=False)

# Offsets on a 1/1024 pixel lattice, so that every phase of the rasterizer's 1/256 pixel grid occurs.
grid = [(((k * 5) % 1024) / 1024 - 0.5, ((k * 37 + 3) % 1024) / 1024 - 0.5) for k in range(256)]
sprites("ml-sprite-pos", [4.0] * 256, 512, 32, grid)
sprites("ml-sprite-pos-frac", [7.3] * 256, 512, 32, grid)

# One sprite wider than the canvas: the row and the column through the centre.
body = sprite(599, 1000) % (599, fmt(world(512, 256, 256)))
write("ml-sprite-clamp", body, [[x + 0.5, 256.5] for x in range(0, 512, 8)] + [[256.5, y + 0.5] for y in range(0, 512, 8) if y != 256], 512)

# Size 2: a PointSet without PointProperties (the page draws it with gl_PointSize 2), and PointProperties sprites of size 2 to 3.
def plain_points(name, size, cell, positions):
    body, probes = "", []
    per_row = size // cell
    for k, (fx, fy) in enumerate(positions):
        cx = (k % per_row) * cell + cell / 2 + fx
        cy = (k // per_row) * cell + cell / 2 + fy
        body += "Shape { geometry PointSet { coord Coordinate { point [ %s ] } } }\n" % fmt(world(size, cx, cy))
        x0, x1, y0, y1 = math.floor(cx - 1) - 1, math.ceil(cx + 1) + 1, math.floor(cy - 1) - 1, math.ceil(cy + 1) + 1
        probes += [[px + 0.5, py + 0.5] for py in range(y0, y1 + 1) for px in range(x0, x1 + 1)]
    write(name, body, probes, size)


plain_points("ml-sprite-two", 512, 32, grid)
rnd = Lcg(13579)
jit2 = lambda: ((rnd.next() - 0.5) * 6, (rnd.next() - 0.5) * 6)
sprites("ml-sprite-low", [2 + k / 256 for k in range(256)], 512, 32, [jit2() for _ in range(256)])
