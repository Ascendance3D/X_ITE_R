#!/usr/bin/env python3
"""FLY / WALK rubber band (F15) and ContentScale (F17) against pinned X_ITE 16.5.0 (issue #51, sub:nav.walk-fly).

  python3 -I -B oracle/tools/rea_nav_overlay.py gen
      Writes the worlds, the stepped scripts and cases.txt to oracle/synthetic-rea-nav-overlay (512x512, dt = 1/30, pointer y from the
      bottom, the script format of x3d-drive and oracle/x_ite-anim.mjs; the keys "contentScale", "browserOptions" and "pixels" are new).
  python3 -I -B oracle/tools/rea_nav_overlay.py record [--only SUBSTRING] [--jobs N]
      Runs oracle/x_ite-anim.mjs three times per case (headless Chrome on the GPU). The summaries must be identical; the first is kept
      as oracle/rea-nav-overlay-baseline/NAME.json (one directory level) and the SHA-256 of the three are printed. A summary is the
      poses and, for a case with "pixels": true, for each captured frame the pixels that differ from the first pixel (the sky color):
      [x, y, r, g, b] with y from the top. A baseline is never taken from Rust.
  python3 -I -B oracle/tools/rea_nav_overlay.py record --msaa 4 [--only SUBSTRING] [--jobs N]
      The same at Multisampling 4 with oracle/x_ite-anim-msaa.mjs --ms 4, for the rubber band cases without the keys "contentScale"
      and "browserOptions" (x_ite-anim-msaa.mjs has neither), into oracle/rea-nav-overlay-msaa4-baseline/NAME.json and its cases.txt
      (one name per line).
  python3 -I -B oracle/tools/rea_nav_overlay.py record --platform apple-m1 --hardware "Apple M1, macOS 27.0.1" [--msaa 4] [--only S] [--jobs N]
      The same recording on another platform (owner decision 2026-11-04, issues #69, #89 and #461; XITE_CHROME and
      XITE_ANGLE_BACKEND name the browser). The NVIDIA baseline is never written: a summary is kept as
      oracle/rea-nav-overlay-<platform>-baseline/NAME.json (with --msaa 4: oracle/rea-nav-overlay-msaa4-<platform>-baseline) only
      when the three runs are identical and differ from the NVIDIA summary, with cases.txt and PROVENANCE.json
      (crates/x3d-viewer/tests/common/reference.rs reads it). Without PIL, the pictures are read with oracle/tools/png_pixels.py
      (the same RGB values).
  python3 -I -B oracle/tools/rea_nav_overlay.py gen-viewport
      Writes the Viewport cases (issue #51: the rubber band when the active layer has a Viewport, or the scene has a Viewport
      grouping node) to oracle/synthetic-rea-nav-overlay-viewport. The other sets are not touched.
  python3 -I -B oracle/tools/rea_nav_overlay.py record --set viewport [--msaa 4] [...]
      Records the Viewport cases into oracle/rea-nav-overlay-viewport-baseline (with --msaa 4:
      oracle/rea-nav-overlay-viewport-msaa4-baseline and its cases.txt; every case, ContentScale included).
  python3 -I -B oracle/tools/rea_nav_overlay.py record --set options --msaa 4 [...]
      Records the rubber band cases with the keys "contentScale" or "browserOptions" (the cases that --msaa 4 of the default set
      leaves out) into oracle/rea-nav-overlay-options-msaa4-baseline and its cases.txt. The existing directories are not written.
"""
import hashlib, json, os, shutil, subprocess, sys
from concurrent.futures import ThreadPoolExecutor

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
syn = os.path.join(root, "oracle", "synthetic-rea-nav-overlay")
syn_vp = os.path.join(root, "oracle", "synthetic-rea-nav-overlay-viewport")
B24 = "oracle/synthetic-rea-b24-nav/"
OWN = "oracle/synthetic-rea-nav-overlay/"
OWN_VP = "oracle/synthetic-rea-nav-overlay-viewport/"
C = (256, 256)
HEADER = "#VRML V2.0 utf8\n# FLY / WALK rubber band oracle world (generated by oracle/tools/rea_nav_overlay.py).\n"
cases = []


def world(name, kind):
    open(os.path.join(syn, name + ".wrl"), "w").write(
        HEADER + f'NavigationInfo {{ type [ "{kind}" ] speed 0.1 }}\nViewpoint {{ position 0 1.6 12 description "start" }}\n'
        "Background { skyColor [ 0.2 0.3 0.5 ] }\n")


def script(name, frames, events, capture, out=None, **extra):
    d = {"size": [512, 512], "t0": 946684800, "dt": 1 / 30, "capture": capture, "dump": [], "frames": frames,
         "events": sorted(events, key=lambda e: e["frame"])}
    d.update(extra)
    json.dump(d, open(os.path.join(out or syn, name + ".json"), "w"), indent=1)


def case(name, w, **kw):
    script(name, **kw)
    cases.append((name, w if "/" in w else OWN + w + ".wrl"))


def vp_case(name, w, **kw):
    script(name, out=syn_vp, **kw)
    cases.append((name, OWN_VP + w + ".wrl"))


VP_HEADER = ("#X3D V4.0 utf8\nPROFILE Interchange\nCOMPONENT Layering:1\nCOMPONENT Navigation:2\n"
             "# Rubber band with a Viewport (generated by oracle/tools/rea_nav_overlay.py gen-viewport).\n")
SKY = "Background { skyColor [ 0.2 0.3 0.5 ] }\n"


def vp_layer_world(name, kind, clip):
    """Layer 0 (the root nodes) has the sky; layer 1, the active layer, has a Viewport with this clipBoundary, the viewer and no
    Background (a layer after the first is transparent), so the whole picture is the sky except the band."""
    open(os.path.join(syn_vp, name + ".wrl"), "w").write(
        VP_HEADER + SKY + "LayerSet {\n activeLayer 1\n order [ 0 1 ]\n layers [\n  Layer {\n   viewport Viewport { clipBoundary [ "
        + " ".join(str(c) for c in clip) + f' ] }}\n   children [\n    NavigationInfo {{ type [ "{kind}" ] speed 0.1 }}\n'
        '    Viewpoint { position 0 1.6 12 description "start" }\n   ]\n  }\n ]\n}\n')


def vp_group_world(name, kind, clip):
    """One layer; a Viewport grouping node (not a layer viewport) holds a small box. X3DViewer.getViewport reads the layer's own
    viewport, so the grouping node changes neither the press test nor the band."""
    open(os.path.join(syn_vp, name + ".wrl"), "w").write(
        VP_HEADER + f'NavigationInfo {{ type [ "{kind}" ] speed 0.1 }}\nViewpoint {{ position 0 1.6 12 description "start" }}\n' + SKY
        + "Viewport {\n clipBoundary [ " + " ".join(str(c) for c in clip) + " ]\n children [\n  Transform { translation 0 -3 -20 children [\n"
        "   Shape { appearance Appearance { material Material { diffuseColor 1 0 0 } } geometry Box { size 1 1 1 } }\n  ] }\n ]\n}\n")


def gen_viewport():
    shutil.rmtree(syn_vp, ignore_errors=True)
    os.makedirs(syn_vp)
    vp_layer_world("vp-layer-walk", "WALK", (0.25, 1, 0.25, 1))
    vp_layer_world("vp-layer-fly", "FLY", (0.1, 0.6, 0.2, 0.9))
    vp_group_world("vp-group-walk", "WALK", (0.25, 1, 0.25, 1))
    cap = [2, 3, 10, 29, 31]
    vp_case("vp-layer-walk-up-right", "vp-layer-walk", frames=40, events=hold(0, C, (330, 340), 30), capture=cap, pixels=True)
    vp_case("vp-layer-walk-leave", "vp-layer-walk", frames=40, events=hold(0, (200, 200), (60, 40), 30), capture=cap, pixels=True)
    vp_case("vp-layer-walk-press-outside", "vp-layer-walk", frames=40, events=hold(0, (60, 60), (200, 200), 30), capture=cap, pixels=True)
    vp_case("vp-layer-fly-down-left", "vp-layer-fly", frames=40, events=hold(0, (150, 300), (80, 140), 30), capture=cap, pixels=True)
    vp_case("vp-layer-fly-pan-middle", "vp-layer-fly", frames=40, events=hold(1, (150, 300), (250, 400), 30), capture=cap, pixels=True)
    vp_case("vp-layer-fly-scale-2", "vp-layer-fly", frames=40, events=hold(0, (150, 300), (80, 140), 30), capture=cap, pixels=True,
            contentScale=2)
    vp_case("vp-layer-walk-scale-0.5", "vp-layer-walk", frames=40, events=hold(0, C, (330, 340), 30), capture=cap, pixels=True,
            contentScale=0.5)
    vp_case("vp-group-walk-up-right", "vp-group-walk", frames=40, events=hold(0, C, (330, 340), 30), capture=cap, pixels=True)
    vp_case("vp-group-walk-press-outside", "vp-group-walk", frames=40, events=hold(0, (60, 60), (200, 200), 30), capture=cap, pixels=True)
    with open(os.path.join(syn_vp, "cases.txt"), "w") as f:
        for name, w in cases:
            f.write(f"{name} {w} {OWN_VP}{name}.json\n")
    print(len(cases), "cases")


def hold(button, start, to, up, f0=2):
    return [{"frame": f0, "type": "mousedown", "button": button, "x": start[0], "y": start[1]},
            {"frame": f0 + 1, "type": "mousemove", "x": to[0], "y": to[1]},
            {"frame": up, "type": "mouseup", "button": button, "x": to[0], "y": to[1]}]


def mods(frame, **kw):
    return {"frame": frame, "type": "mods", "shift": kw.get("shift", False), "ctrl": kw.get("ctrl", False), "alt": kw.get("alt", False)}


def gen():
    shutil.rmtree(syn, ignore_errors=True)
    os.makedirs(syn)
    world("nav-walk", "WALK")
    world("nav-fly", "FLY")
    cap = [2, 3, 10, 29, 31]
    # F15: the drawn rubber band (pixels). Frame 2 is the press (the two ends are the same: nothing is drawn), 29 is the last frame of
    # the hold, 31 is after the release.
    for name, w, to in (("walk-up-right", "nav-walk", (330, 340)), ("fly-down-left", "nav-fly", (180, 160)), ("walk-vertical", "nav-walk", (256, 330)),
                        ("fly-horizontal", "nav-fly", (340, 256)), ("walk-horizontal-left", "nav-walk", (170, 256)),
                        ("fly-vertical-up", "nav-fly", (256, 180)), ("walk-long", "nav-walk", (500, 20)), ("fly-short", "nav-fly", (258, 255))):
        case("rubber-" + name, w, frames=40, events=hold(0, C, to, 30), capture=cap, pixels=True)
    case("rubber-pan-middle", "nav-walk", frames=40, events=hold(1, C, (200, 300), 30), capture=cap, pixels=True)
    case("rubber-pan-alt", "nav-fly", frames=40, events=[mods(1, alt=True)] + hold(0, C, (310, 200), 30) + [mods(35)], capture=cap, pixels=True)
    case("rubber-two-buttons", "nav-walk", frames=40, events=hold(0, C, (330, 340), 30) + [{"frame": 5, "type": "mousedown", "button": 1, "x": 100, "y": 100},
         {"frame": 6, "type": "mousemove", "x": 120, "y": 90}, {"frame": 8, "type": "mouseup", "button": 1, "x": 120, "y": 90}], capture=cap, pixels=True)
    case("rubber-wheel-roll", "nav-fly", frames=40, events=hold(0, C, (330, 340), 30) + [{"frame": 12, "type": "wheel", "deltaY": -100, "x": 256, "y": 256}],
         capture=cap, pixels=True)
    case("rubber-ctrl-look", "nav-fly", frames=40, events=[mods(1, ctrl=True)] + hold(0, C, (330, 340), 30) + [mods(35)], capture=cap, pixels=True)
    case("rubber-option-off", "nav-walk", frames=40, events=hold(0, C, (330, 340), 30), capture=cap, pixels=True, browserOptions={"Rubberband": False})
    case("rubber-viewer-switch", "nav-walk", frames=40, events=hold(0, C, (330, 340), 30) + [{"frame": 15, "type": "viewer", "name": "FLY"}],
         capture=cap + [16], pixels=True)
    for cs in (2, 1.5, 0.5):
        case(f"rubber-scale-{cs}", "nav-fly", frames=40, events=hold(0, C, (330, 340), 30), capture=cap, pixels=True, contentScale=cs)
    # F17: the pointer is in drawing-buffer pixels (CSS pixels x ContentScale) and the viewer divides the direction by ContentScale: the
    # speed and the turn rate do not depend on it. Poses only.
    walk, fly = B24 + "nav-speed-1.wrl", B24 + "nav-speed-fly-1.wrl"
    for cs in (2, 1.5, 0.5, 3):
        case(f"scale-walk-forward-{cs}", walk, frames=90, events=hold(0, C, (256, 330), 73), capture=[20, 50, 90], contentScale=cs)
    case("scale-walk-turn-2", walk, frames=90, events=hold(0, C, (330, 300), 73), capture=[20, 50, 90], contentScale=2)
    case("scale-fly-diagonal-1.5", fly, frames=90, events=hold(0, C, (300, 340), 73), capture=[20, 50, 90], contentScale=1.5)
    case("scale-fly-shift-2", fly, frames=90, events=[mods(1, shift=True)] + hold(0, C, (256, 330), 73), capture=[20, 50, 90], contentScale=2)
    case("scale-walk-alt-pan-2", walk, frames=90, events=[mods(1, alt=True)] + hold(0, C, (300, 220), 73) + [mods(80)], capture=[20, 50, 90], contentScale=2)
    case("scale-fly-middle-pan-0.5", fly, frames=90, events=hold(1, C, (200, 300), 73), capture=[20, 50, 90], contentScale=0.5)
    case("scale-fly-ctrl-look-2", fly, frames=90, events=[mods(1, ctrl=True)] + hold(0, C, (330, 300), 73) + [mods(80)], capture=[20, 50, 90], contentScale=2)
    with open(os.path.join(syn, "cases.txt"), "w") as f:
        for name, w in cases:
            f.write(f"{name} {w} {OWN}{name}.json\n")
    print(len(cases), "cases")


def _rgb_reader():
    """path -> ((w, h), px) with px[x, y] an (r, g, b) tuple: PIL where installed, else oracle/tools/png_pixels.py."""
    try:
        from PIL import Image

        def read(path):
            im = Image.open(path).convert("RGB")
            return im.size, im.load()
    except ImportError:
        import importlib.util
        spec = importlib.util.spec_from_file_location("png_pixels", os.path.join(os.path.dirname(os.path.abspath(__file__)), "png_pixels.py"))
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)

        class Px:
            def __init__(self, rows):
                self.rows = rows

            def __getitem__(self, xy):
                x, y = xy
                return tuple(self.rows[y][4 * x:4 * x + 3])

        def read(path):
            w, h, rows = module.pixels(path)
            return (w, h), Px(rows)
    return read


def summary(d, with_pixels):
    read = _rgb_reader()
    js = json.load(open(os.path.join(d, "js.json")))
    out = {"ok": js.get("ok"), "warmupFrames": js.get("warmupFrames"), "poses": js.get("poses"), "geometry": js.get("geometry")}

    if with_pixels:
        frames = {}
        for name in sorted(os.listdir(os.path.join(d, "png")), key=lambda n: int(n.split(".")[0])):
            (w, h), px = read(os.path.join(d, "png", name))
            bg = px[0, 0]
            frames[name.split(".")[0]] = {"size": [w, h], "background": list(bg),
                                          "pixels": [[x, y, *px[x, y]] for y in range(h) for x in range(w) if px[x, y] != bg]}
        out["frames"] = frames

    return out


def msaa_case(script_path):
    s = json.load(open(os.path.join(root, script_path)))
    return s.get("pixels", False) and "contentScale" not in s and "browserOptions" not in s


def options_case(script_path):
    s = json.load(open(os.path.join(root, script_path)))
    return s.get("pixels", False) and ("contentScale" in s or "browserOptions" in s)


# set: (case table directory, baseline stem, the cases recorded at MSAA above 0)
SETS = {"main": (syn, "rea-nav-overlay", msaa_case), "viewport": (syn_vp, "rea-nav-overlay-viewport", lambda p: True),
        "options": (syn, "rea-nav-overlay-options", options_case)}


def record(only, jobs, msaa=0, platform=None, hardware="", which="main"):
    table_dir, base, msaa_filter = SETS[which]
    assert which != "options" or msaa, "--set options is for --msaa above 0 (the MSAA 0 cases are in the default set)"
    table = [l.split() for l in open(os.path.join(table_dir, "cases.txt")).read().splitlines() if l.strip()]
    if msaa:
        table = [c for c in table if msaa_filter(c[2])]
    table = [c for c in table if not only or only in c[0]]
    stem = f"{base}-msaa{msaa}" if msaa else base
    nvidia = os.path.join(root, "oracle", f"{stem}-baseline")
    dest = os.path.join(root, "oracle", f"{stem}-{platform}-baseline") if platform else nvidia
    if platform:
        assert os.environ.get("XITE_CHROME") and os.environ.get("XITE_ANGLE_BACKEND"), "set XITE_CHROME and XITE_ANGLE_BACKEND"
    else:
        os.makedirs(dest, exist_ok=True)
    anim = ["x_ite-anim-msaa.mjs"] if msaa else ["x_ite-anim.mjs"]

    def run(case):
        name, world, script_path = case
        pixels = json.load(open(os.path.join(root, script_path))).get("pixels", False)
        texts = []
        for i in (1, 2, 3):
            d = f"/tmp/nav-overlay-record{'-' + platform if platform else ''}/{name}-{i}"
            shutil.rmtree(d, ignore_errors=True)
            os.makedirs(d)
            subprocess.run(["node", os.path.join(root, "oracle", anim[0]), world, script_path, "--out", os.path.join(d, "js.json"),
                            "--png-dir", os.path.join(d, "png")] + (["--ms", str(msaa)] if msaa else []),
                           check=True, cwd=root, timeout=300, capture_output=True)
            texts.append(json.dumps(summary(d, pixels), sort_keys=True, indent=0))
            shutil.rmtree(d, ignore_errors=True)
        return name, texts

    with ThreadPoolExecutor(jobs) as ex:
        results = list(ex.map(run, table))

    bad, kept, prov = 0, [], {}
    rows = {c[0]: " ".join(c) for c in table}
    for name, texts in results:
        digests = [hashlib.sha256(t.encode()).hexdigest() for t in texts]
        same = len(set(digests)) == 1
        bad += not same
        print(f"{name}: {'identical' if same else 'DIFFER'} {' '.join(x[:12] for x in digests)} {len(texts[0])} bytes")
        if not same:
            continue
        if platform:
            if open(os.path.join(nvidia, name + ".json")).read() == texts[0] + "\n":
                print(f"{name}: equal to the NVIDIA summary, not kept")
                continue
            os.makedirs(dest, exist_ok=True)
            kept.append(name)
            prov[name] = dict(run_sha256=digests)
        open(os.path.join(dest, name + ".json"), "w").write(texts[0] + "\n")
    if msaa and not platform and not only:
        open(os.path.join(dest, "cases.txt"), "w").write("".join(n + "\n" for n, _ in results))
    if platform and kept:
        import datetime
        table_path = os.path.join(dest, "cases.txt")
        old = {l.split()[0]: l for l in open(table_path).read().splitlines() if l.strip()} if os.path.exists(table_path) else {}
        old.update({n: rows[n] for n in kept})
        open(table_path, "w").write("".join(old[k] + "\n" for k in sorted(old)))
        pfile = os.path.join(dest, "PROVENANCE.json")
        cur = json.load(open(pfile)) if os.path.exists(pfile) else {"cases": {}}
        chrome = subprocess.run([os.environ["XITE_CHROME"], "--version"], capture_output=True, text=True).stdout.strip()
        pinned = open(os.path.join(root, "oracle", "x_ite-pin", "PINNED_COMMIT")).read().strip()
        cur.update(platform=platform, hardware=hardware, chrome=chrome, angle_backend=os.environ["XITE_ANGLE_BACKEND"],
                   pinned_x_ite="16.5.0 " + pinned, recorder=f"oracle/tools/rea_nav_overlay.py record (oracle/{anim[0]}{' --ms ' + str(msaa) if msaa else ''})",
                   user_agent=os.environ.get("XITE_USER_AGENT", "(the browser's own)"),
                   recorded=datetime.date.today().isoformat(), rule="3 identical summaries; kept only where the NVIDIA summary differs")
        cur["cases"].update(prov)
        json.dump(cur, open(pfile, "w"), indent=1, sort_keys=True)
    if platform:
        print(f"{stem}/{platform}: {len(results)} cases; {len(kept)} overrides kept")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    a = sys.argv[1:]
    opt = lambda n, d=None: a[a.index(n) + 1] if n in a else d
    if a and a[0] == "gen":
        gen()
    elif a and a[0] == "gen-viewport":
        gen_viewport()
    elif a and a[0] == "record":
        record(opt("--only"), int(opt("--jobs", "6")), int(opt("--msaa", "0")), opt("--platform"), opt("--hardware", ""), opt("--set", "main"))
    else:
        sys.exit(__doc__)
