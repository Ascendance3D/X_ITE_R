    script(f"{t}-ctrl-look", last + 20, [mods(2, ctrl=True)] + ev + [mods(last + 2)], capture=[8, 18, last + 20])
    case(f"{t}-ctrl-look", w)
    ev, last = drag(0, C, [(256 + 10 * i, 256 + 14 * i) for i in range(1, 14)], f0=3, end_extra=30)
    script(f"{t}-alt-pan", last + 10, [mods(2, alt=True)] + ev + [mods(last + 2)], capture=[8, 18, last + 10])
    case(f"{t}-alt-pan", w)
