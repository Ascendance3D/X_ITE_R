    case(f"{t}-middle-pan", w)
    script(f"{t}-wheel-roll", 70, wheel(range(2, 7), -100) + wheel(range(20, 25), 100) + wheel(range(40, 43), -100), capture=[5, 12, 30, 70])
    case(f"{t}-wheel-roll", w)
    ev, _ = hold(0, C, (256, 330), 60)
    script(f"{t}-wall", 90, ev, capture=[20, 40, 60, 90], probes=True)
    case(f"{t}-wall", w)
    ev, last = drag(0, C, [(256 + 9 * i, 256 + 14 * i) for i in range(1, 16)], end_extra=45)
    script(f"{t}-wall-slide", last + 45, ev + [mods(2, shift=True), mods(last + 4)], capture=[20, 40, last + 45], probes=True)
    case(f"{t}-wall-slide", w)
    # two buttons: a second press while one is held is ignored; release order
    ev = [{"frame": 2, "type": "mousedown", "button": 0, "x": 256, "y": 256}, {"frame": 3, "type": "mousemove", "x": 256, "y": 320},
          {"frame": 6, "type": "mousedown", "button": 1, "x": 256, "y": 256}, {"frame": 8, "type": "mouseup", "button": 1, "x": 256, "y": 256},
          {"frame": 30, "type": "mouseup", "button": 0, "x": 256, "y": 320}]
    script(f"{t}-two-buttons", 50, ev, capture=[10, 30, 50])
    case(f"{t}-two-buttons", w)
    # a pointer press outside nothing: the canvas is the whole page; press at the border
    ev, _ = hold(0, (2, 2), (60, 90), 30)
    script(f"{t}-corner", 60, ev, capture=[30, 60])
    case(f"{t}-corner", w)

