#!/usr/bin/env python3
"""REA batch 09 navigation oracle: worlds (oracle/synthetic-rea-b09-nav/*.wrl) and stepped event
scripts (oracle/synthetic-rea-b09-nav/scripts/*.json) for the WALK, FLY, NONE, EXAMINE, PLANE and
LOOKAT viewers, collision, gravity, terrain following and viewpoint transitions. 512x512, dt = 1/30,
pointer y measured from the bottom. The cases (name world script) are listed in cases.txt.

  python3 -I oracle/tools/gen_rea_b09_nav.py
"""
import json, os, math

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "synthetic-rea-b09-nav"))
os.makedirs(os.path.join(root, "scripts"), exist_ok=True)
cases = []

BOX = lambda cx, cy, cz, sx, sy, sz, color="0.6 0.6 0.6": (
    f"Transform {{ translation {cx} {cy} {cz} children Shape {{ appearance Appearance {{ material Material {{ diffuseColor {color} }} }} "
    f"geometry Box {{ size {sx} {sy} {sz} }} }} }}")


X3D_HEADER = "#X3D V4.0 utf8\nPROFILE Immersive\nCOMPONENT X_ITE:1\n# REA batch 09 navigation oracle world (generated by oracle/tools/gen_rea_b09_nav.py).\n"


def world(name, nav, viewpoints, body, header=None):
    text = header or "#VRML V2.0 utf8\n# REA batch 09 navigation oracle world (generated by oracle/tools/gen_rea_b09_nav.py).\n"
    text += nav + "\n" + "\n".join(viewpoints) + "\n" + body + "\n"
    open(os.path.join(root, name + ".wrl"), "w").write(text)


def probe_directions():
    """Directions for the closest-object probes after the last frame: 12 azimuths at 5 elevations, down and up."""
    out = []
    for el in (-60, -30, 0, 30, 60):
        for az in range(0, 360, 30):
            a, e = math.radians(az), math.radians(el)
            out.append([round(math.cos(e) * math.sin(a), 6), round(math.sin(e), 6), round(-math.cos(e) * math.cos(a), 6)])
    return out + [[0, -1, 0], [0, 1, 0], [0.3, -1, 0.1], [-0.2, -1, -0.3]]


def script(name, frames, events, capture=None, dump=None, probes=False):
    ev = sorted(events, key=lambda e: e["frame"])
    d = {"size": [512, 512], "t0": 946684800, "dt": 1 / 30, "capture": capture if capture is not None else [frames], "dump": dump or [], "frames": frames, "events": ev}
    if probes:
        d["collisionProbes"] = probe_directions()
    json.dump(d, open(os.path.join(root, "scripts", name + ".json"), "w"), indent=1)


def case(name, w, s=None):
    cases.append((name, w, s or name))


def drag(button, start, pts, f0=2, per_frame=1, end_extra=0):
    ev = [{"frame": f0, "type": "mousedown", "button": button, "x": start[0], "y": start[1]}]
    f = f0 + 1
    i = 0
    while i < len(pts):
        for p in pts[i:i + per_frame]:
            ev.append({"frame": f, "type": "mousemove", "x": p[0], "y": p[1]})
        i += per_frame
        f += 1
    ev.append({"frame": f + end_extra, "type": "mouseup", "button": button, "x": pts[-1][0], "y": pts[-1][1]})
    return ev, f + end_extra


def hold(button, start, to, frames, f0=2):
    """mousedown, one move to `to`, hold for `frames` frames, mouseup."""
    return [{"frame": f0, "type": "mousedown", "button": button, "x": start[0], "y": start[1]},
            {"frame": f0 + 1, "type": "mousemove", "x": to[0], "y": to[1]},
            {"frame": f0 + 1 + frames, "type": "mouseup", "button": button, "x": to[0], "y": to[1]}], f0 + 1 + frames


def mods(frame, shift=False, ctrl=False, alt=False):
    return {"frame": frame, "type": "mods", "shift": shift, "ctrl": ctrl, "alt": alt}


def wheel(frames, delta, x=256, y=256):
    return [{"frame": f, "type": "wheel", "deltaY": delta, "x": x, "y": y} for f in frames]


def key(frame, k):
    return {"frame": frame, "type": "key", "key": k}


C = (256, 256)

# --- worlds ------------------------------------------------------------------------------------
def rbox(cx, cy, cz, sx, sy, sz, ry, color="0.7 0.5 0.3"):
    return (f"Transform {{ translation {cx} {cy} {cz} rotation 0 1 0 {ry} children Shape {{ appearance Appearance {{ material Material {{ diffuseColor {color} }} }} "
            f"geometry Box {{ size {sx} {sy} {sz} }} }} }}")


def path_step(t, h):
    """A step on the path of the "side" viewpoint (8, 1.6, 8), heading (-0.565, -0.825): center and scale."""
    return f"{8 - 0.565 * t:.3f} {h / 2:.3f} {8 - 0.825 * t:.3f}", f"3 {h} 1"


