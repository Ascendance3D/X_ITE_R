#!/usr/bin/env python3
"""E18 of docs/reports/NAV_ITEM_LISTS.md (sub:nav.examine): a synthetic clean-room world for the X10 rotate and zoom regression scripts.

  python3 -I -B oracle/tools/gen_rea_x10_synthetic.py

Writes oracle/synthetic-rea-b24-nav/x10-stress.wrl and oracle/synthetic-rea-b24-nav/cases-x10.txt (`name world script msaa`). New files
only. The scripts are the existing ones of oracle/x10-scripts (made by gen_x10_clip.py, gen_x10_rotate_zoom.py and the msaa-orrery
scripts); they are synthetic input, only the world they were first used with is private and is not used here. The world has the same
stress, written for this test: large and small shapes around a center of rotation (near clipping when the camera zooms in or out
and rotates), a ground plane that the camera can cut through, and an orrery-like chain of nested animated Transforms (a TimeSensor
and an OrientationInterpolator per level, the time is the harness's frame clock). Nothing here is copied from a historical world.
Cases: MSAA 0 and 4, 512x512 and 1024x768 (the size is the script's).
"""
import math, os

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
d = os.path.join(root, "oracle", "synthetic-rea-b24-nav")


def spinner(name, cycle):
    keys = [i / 4 for i in range(5)]
    vals = " ".join(f"0 1 0 {a:.6f}," for a in (0, math.pi / 2, math.pi, 3 * math.pi / 2, 2 * math.pi)).rstrip(",")
    return (f"DEF T_{name} TimeSensor {{ cycleInterval {cycle} loop TRUE }}\n"
            f"DEF O_{name} OrientationInterpolator {{ key [ {' '.join(f'{k:g}' for k in keys)} ] keyValue [ {vals} ] }}\n"
            f"ROUTE T_{name}.fraction_changed TO O_{name}.set_fraction\n"
            f"ROUTE O_{name}.value_changed TO X_{name}.set_rotation\n")


def shape(geom, color):
    return f"Shape {{ appearance Appearance {{ material Material {{ diffuseColor {color} }} }} geometry {geom} }}"


WORLD = f"""#VRML V2.0 utf8
# E18 synthetic stress world (generated by oracle/tools/gen_rea_x10_synthetic.py). Clean-room: written for this test.
NavigationInfo {{ type [ "EXAMINE" ] }}
Viewpoint {{ position 0 3 18 orientation 1 0 0 -0.12 fieldOfView 0.785 description "stress front" }}
DirectionalLight {{ direction -0.3 -1 -0.5 intensity 0.9 }}
# A ground plane and a wall: large flat shapes that the camera can cut through when it zooms in.
Transform {{ translation 0 -4 0 children {shape("Box { size 14 0.2 14 }", "0.45 0.5 0.45")} }}
Transform {{ translation 0 3 -7 children {shape("Box { size 9 6 0.3 }", "0.6 0.55 0.5")} }}
# A thin ring of boxes and posts near the middle: small shapes right at the center of rotation.
Transform {{ translation 0 0 0 children [
  {shape("Sphere { radius 1.6 }", "0.9 0.75 0.2")}
  Transform {{ translation 2.5 0 0 children {shape("Box { size 0.2 3 0.2 }", "0.8 0.2 0.2")} }}
  Transform {{ translation -2.5 0 0 children {shape("Box { size 0.2 3 0.2 }", "0.2 0.2 0.8")} }}
] }}
# The orrery-like chain: arm -> planet -> moon, each level a Transform that an interpolator turns.
DEF X_A Transform {{ children [
  Transform {{ translation 6 0 0 children [
    {shape("Sphere { radius 0.9 }", "0.2 0.6 0.9")}
    Transform {{ translation 0 -0.3 0 children {shape("Cylinder { radius 1.6 height 0.04 }", "0.7 0.7 0.7")} }}
    DEF X_B Transform {{ children [
      Transform {{ translation 2.2 0 0 children [
        {shape("Sphere { radius 0.4 }", "0.9 0.9 0.9")}
        DEF X_C Transform {{ children Transform {{ translation 0 0.9 0 children {shape("Cone { bottomRadius 0.15 height 0.5 }", "0.9 0.4 0.1")} }} }}
      ] }}
    ] }}
  ] }}
] }}
{spinner("A", 8)}{spinner("B", 5)}{spinner("C", 2)}"""

# (script, msaa) of the cases: the scripts of oracle/x10-scripts.
CLIP = ["clip-rotate-large", "clip-zoom-in-rotate", "clip-zoom-out-rotate", "clip-pan-zoom-drag"]
cases = []
for s in CLIP:
    cases += [(s, 0), (s + "-1024-multi", 0)]
cases += [("clip-rotate-large", 4), ("clip-zoom-in-rotate", 4), ("clip-rotate-large-1024", 4), ("clip-zoom-out-rotate-1024-multi", 4)]
cases += [(f"rotate-then-zoom-in-r{k}", 0) for k in (0, 1, 2, 5)]
cases += [("rotate-then-zoom-out-r0", 0), ("rotate-then-zoom-out-r2", 0), ("rotate-during-zoom-in-d9", 0), ("rotate-during-zoom-out-d9", 0)]
cases += [("rotate-then-zoom-in-r2", 4), ("rotate-then-zoom-out-r0", 4)]
for s in ("msaa-orrery-rotate", "msaa-orrery-zoom12", "msaa-orrery-zoom22"):
    cases += [(s, 0), (s, 4)]

open(os.path.join(d, "x10-stress.wrl"), "w").write(WORLD)
world = "oracle/synthetic-rea-b24-nav/x10-stress.wrl"
open(os.path.join(d, "cases-x10.txt"), "w").write(
    "".join(f"x10-{s}-msaa{m} {world} oracle/x10-scripts/{s}.json {m}\n" for s, m in cases))
print(len(cases), "cases")
