#!/usr/bin/env python3
"""Text geometry under InstancedShape against pinned X_ITE 16.5.0 (oracle/synthetic-instanced-text). Authored, no historical assets.
512x512, Viewpoint at 0 0 12, dt = 1/30, `settle` true (the default font arrives between two frames in X_ITE and Rust alike).

  it-static   plain Shape + Text (control) and InstancedShapes with Text: three translations, scales / rotations / scaleOrientations /
              centers (fewer values than instances), FontStyle (size, justify, spacing, vertical), `length` / `maxExtent`, no instance
              field (no instance is drawn), a transparent Material
  it-extra    PixelTexture on instanced Text, solid TRUE with instances turned about Y, bboxDisplay and an explicit bbox, `length` per
              line, an empty string, visible FALSE
  it-pick     TouchSensor pointing at instanced Text: pickProbes grid (hit id, point, normal, texCoord), bit for bit
  it-runtime  a KeySensor drives a Script that changes `string`, FontStyle fields, the instance fields and `geometry` of an
              InstancedShape at run time (a picture after each key)

  python3 -I -B oracle/tools/gen_instanced_text.py
"""
import json, os

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "synthetic-instanced-text"))
os.makedirs(root, exist_ok=True)
HEAD = ("#X3D V4.0 utf8\nPROFILE Full\nCOMPONENT X_ITE:1\nCOMPONENT Scripting:1\n"
        "# Instanced Text oracle world (generated by oracle/tools/gen_instanced_text.py).\n")
BG = "DEF V1 Viewpoint { position 0 0 12 }\nNavigationInfo { type \"NONE\" headlight TRUE }\nBackground { skyColor 0.12 0.14 0.2 }\n"
MAT = lambda c: f"Appearance {{ material Material {{ diffuseColor {c} emissiveColor {c} }} }}"


def write(name, text):
    open(os.path.join(root, name + ".wrl"), "w").write(text)


def script(name, frames, events, capture):
    d = {"settle": True, "console": True, "size": [512, 512], "t0": 946684800, "dt": 1 / 30, "frames": frames, "capture": capture,
         "dump": sorted(set(capture + [frames - 1])), "events": sorted(events, key=lambda e: e["frame"])}
    with open(os.path.join(root, name + ".json"), "w") as f:
        json.dump(d, f, indent=1)
        f.write("\n")


def T(tr, body):
    return f"Transform {{ translation {tr} children [ {body} ] }}\n"


def txt(strings, fs="", extra=""):
    s = " ".join(f'"{x}"' for x in strings)
    f = f"fontStyle FontStyle {{ {fs} }} " if fs else ""
    return f"Text {{ string [ {s} ] {f}{extra} solid FALSE }}"


# ---- it-static ------------------------------------------------------------------------------------------------------------
w = HEAD + BG
# control: the same Text in a plain Shape
w += T("-4.2 3.6 0", f"Shape {{ appearance {MAT('0.95 0.95 0.95')} geometry {txt(['Ab'], 'size 0.8')} }}")
# three translations
w += T("-1.8 3.6 0", f"InstancedShape {{ appearance {MAT('0.95 0.6 0.3')} translations [ 0 0 0, 1.8 0.4 0, 3.6 -0.3 0 ] geometry {txt(['Ab'], 'size 0.8')} }}")
# scales / rotations / scaleOrientations / centers, with fewer values than instances
w += T("-4.2 1.4 0", f"InstancedShape {{ appearance {MAT('0.4 0.9 0.5')} translations [ 0 0 0, 2.8 0.3 0, 5.6 0 0 ] scales [ 1 1 1, 1.4 0.6 1 ] "
       f"rotations [ 0 0 1 0.3, 0 0 1 -0.4 ] scaleOrientations [ 0 0 1 0.5 ] centers [ 0.3 0 0 ] geometry {txt(['Xy'], 'size 0.7')} }}")
# FontStyle: justify MIDDLE and two lines, spacing
w += T("-2.6 -0.6 0", f"InstancedShape {{ appearance {MAT('0.5 0.7 1')} translations [ 0 0 0, 4 0 0 ] "
       f"geometry {txt(['One', 'Two'], 'size 0.55 spacing 1.2 justify [ \"MIDDLE\" \"MIDDLE\" ]')} }}")
# vertical, top-to-bottom
w += T("3.3 0.1 0", f"InstancedShape {{ appearance {MAT('0.9 0.4 0.7')} translations [ 0 0 0, 0.8 0 0 ] "
       f"geometry {txt(['abc'], 'size 0.5 horizontal FALSE topToBottom TRUE')} }}")
# length / maxExtent
w += T("-4.3 -3 0", f"InstancedShape {{ appearance {MAT('1 0.9 0.3')} translations [ 0 0 0, 3.4 0 0 ] scales [ 1 1 1, 0.7 1.4 1 ] "
       f"geometry {txt(['Wide text'], 'size 0.5', 'length [ 3 ] maxExtent 2.2')} }}")
# no instance field: a single instance at the origin of the shape
w += T("1.0 -3 0", f"InstancedShape {{ appearance {MAT('0.8 0.8 0.8')} geometry {txt(['Single'], 'size 0.6')} }}")
# transparent Material
w += T("3.3 -3 0", f"InstancedShape {{ appearance Appearance {{ material Material {{ diffuseColor 1 0.2 0.2 emissiveColor 0.5 0.1 0.1 transparency 0.5 }} }} "
       f"translations [ 0 0 0, 0.3 0.25 -0.2 ] geometry {txt(['Tr'], 'size 0.8')} }}")
write("it-static", w)
script("it-static", 12, [], [10])

# ---- it-runtime -----------------------------------------------------------------------------------------------------------
w = HEAD + BG
w += ("DEF I InstancedShape { appearance " + MAT("0.95 0.6 0.3") + " translations [ -3 1.5 0, 0 1.5 0, 3 1.5 0 ] geometry DEF TX Text { string [ \"Ab\" ] "
      "fontStyle DEF FS FontStyle { size 1 } solid FALSE } }\n")
w += T("0 -2 0", "Shape { appearance " + MAT("0.95 0.95 0.95") + " geometry DEF TC Text { string [ \"Ctl\" ] fontStyle DEF FC FontStyle { size 1 } solid FALSE } }")
w += T("0 -4 0", "DEF J InstancedShape { appearance " + MAT("0.5 0.8 0.9") + " translations [ -2 0 0, 2 0 0 ] geometry Box { size 1 1 1 } }")
w += ("DEF K KeySensor { }\nDEF R Script {\n  directOutput TRUE\n  inputOnly SFString on_key\n  inputOutput SFString log \"\"\n"
      "  initializeOnly SFNode i USE I\n  initializeOnly SFNode j USE J\n  initializeOnly SFNode tx USE TX\n  initializeOnly SFNode fs USE FS\n"
      "  initializeOnly SFNode tc USE TC\n  initializeOnly SFNode fc USE FC\n  url \"javascript:\n"
      "function on_key (k)\n{\n   log = log + 'K' + k + ' ';\n"
      "   if (k == 'a') { tx .string = new MFString ('Chg'); tc .string = new MFString ('Chg'); }\n"
      "   if (k == 'b') { fs .size = 1.6; fc .size = 1.6; }\n"
      "   if (k == 'c') i .scales = new MFVec3f (new SFVec3f (1, 1, 1), new SFVec3f (1.4, 0.5, 1), new SFVec3f (0.6, 1.5, 1));\n"
      "   if (k == 'd') i .rotations = new MFRotation (new SFRotation (0, 0, 1, 0.4), new SFRotation (0, 0, 1, -0.4));\n"
      "   if (k == 'e') { fs .justify = new MFString ('MIDDLE', 'MIDDLE'); fc .justify = new MFString ('MIDDLE', 'MIDDLE'); }\n"
      "   if (k == 'f') i .translations = new MFVec3f (new SFVec3f (-3, 1.5, 0), new SFVec3f (3, 1.5, 0));\n"
      "   if (k == 'g') j .geometry = tc;\n"
      "   if (k == 'h') j .translations = new MFVec3f (new SFVec3f (0, 0, 0));\n"
      "   if (k == 'i') { tx .string = new MFString ('One', 'Two'); tc .string = new MFString ('One', 'Two'); }\n"
      "   if (k == 'j') i .geometry = null;\n"
      "}\n\"\n}\nROUTE K.keyPress TO R.on_key\n")
write("it-runtime", w)
letters = "abcdefghij"
start, step = 6, 8
ev = [{"frame": start + step * n, "type": "key", "key": c} for n, c in enumerate(letters)]
script("it-runtime", start + step * len(letters) + 6, ev, [start - 2] + [start + step * n + 3 for n in range(len(letters))])

# ---- it-extra -------------------------------------------------------------------------------------------------------------
PIX = 'texture PixelTexture { image 2 2 3 0xff0000 0x00ff00 0x0000ff 0xffff00 }'
w = HEAD + BG
# PixelTexture on Text instances (texture coordinates of the Text, not of the instance)
w += T("-3.6 3.2 0", f"InstancedShape {{ appearance Appearance {{ material Material {{ }} {PIX} }} translations [ 0 0 0, 3.4 0.3 0 ] "
       f"scales [ 1 1 1, 1.3 1.3 1 ] geometry {txt(['Tex'], 'size 1')} }}")
# solid TRUE: instances turned about Y show the back of the Text (culled)
w += T("-3.6 0.8 0", f"InstancedShape {{ appearance {MAT('0.9 0.9 0.4')} translations [ 0 0 0, 2.2 0 0, 4.4 0 0 ] "
       f"rotations [ 0 0 1 0, 0 1 0 3.14159, 0 1 0 1.2 ] geometry Text {{ string [ \"Sd\" ] fontStyle FontStyle {{ size 0.9 }} solid TRUE }} }}")
# bboxDisplay and an explicit bbox around instances
w += T("-3.6 -1.6 0", f"InstancedShape {{ bboxDisplay TRUE appearance {MAT('0.6 0.9 0.9')} translations [ 0 0 0, 2.6 0.4 0 ] "
       f"geometry {txt(['Bx'], 'size 0.8')} }}")
w += T("1.6 -1.6 0", f"InstancedShape {{ bboxDisplay TRUE bboxCenter 0.6 0 0 bboxSize 2.4 1 1 appearance {MAT('0.9 0.6 0.9')} translations [ 0 0 0 ] "
       f"geometry {txt(['Bb'], 'size 0.8')} }}")
# a Text with several lines and `length` under many instances, a Text with an empty string, a visible FALSE InstancedShape
w += T("-3.6 -3.8 0", f"InstancedShape {{ appearance {MAT('0.8 0.8 1')} translations [ 0 0 0, 1.8 0 0, 3.6 0 0 ] scales [ 0.8 0.8 0.8 ] "
       f"geometry {txt(['Aa', 'Bb'], 'size 0.5', 'length [ 1.2 0.8 ]')} }}")
w += T("3.4 -3.8 0", f"InstancedShape {{ appearance {MAT('1 1 1')} translations [ 0 0 0 ] geometry {txt([''], 'size 0.5')} }}")
w += T("1.0 3.2 0", f"InstancedShape {{ visible FALSE appearance {MAT('1 0 0')} translations [ 0 0 0 ] geometry {txt(['Hidden'], 'size 0.8')} }}")
write("it-extra", w)
script("it-extra", 12, [], [10])

# ---- it-pick --------------------------------------------------------------------------------------------------------------
SIZE = 512
grid = [[3.25 + i * 10, 3.25 + j * 10] for j in range(51) for i in range(51)]
w = HEAD + "COMPONENT PointingDeviceSensor:1\n" + BG
w += T("-3.8 2.2 0", f"TouchSensor {{ }} InstancedShape {{ appearance {MAT('0.95 0.6 0.3')} translations [ 0 0 0, 2.8 0.5 0, 5.6 -0.4 0 ] "
       f"scales [ 1 1 1, 1.4 0.8 1 ] rotations [ 0 0 1 0.3 ] geometry {txt(['Hit'], 'size 1')} }}")
w += T("-3.8 -0.8 0", f"TouchSensor {{ }} InstancedShape {{ appearance {MAT('0.4 0.9 0.5')} translations [ 0 0 0, 0.6 0.2 0.3 ] "
       f"geometry {txt(['One', 'Two'], 'size 0.8 justify [ \"MIDDLE\" \"MIDDLE\" ]')} }}")
w += T("0.5 -0.8 0", f"InstancedShape {{ pointerEvents FALSE appearance {MAT('0.4 0.5 0.9')} translations [ 0 0 0, 2 0 0 ] geometry {txt(['No'], 'size 0.8')} }}")
w += T("-3.8 -3.4 0", f"TouchSensor {{ }} Shape {{ appearance {MAT('0.8 0.8 0.8')} geometry Box {{ size 1.2 1 0.2 }} }} "
       f"InstancedShape {{ appearance {MAT('1 0.9 0.3')} translations [ 0 0 0.4, 2 0 -0.4 ] geometry {txt(['Fr'], 'size 1')} }}")
write("it-pick", w)
d = {"size": [SIZE, SIZE], "t0": 946684800, "dt": 1 / 30, "settle": True, "console": True, "frames": 12, "capture": [10], "dump": [10, 11],
     "events": [], "pickProbes": grid}
# One row of probes per line, so that the file stays small and a diff of it stays readable.
rows = ",\n  ".join(json.dumps(grid[r * 51:(r + 1) * 51], separators=(",", ":"))[1:-1] for r in range(51))
head = json.dumps({k: v for k, v in d.items() if k != "pickProbes"}, separators=(",", ":"))
open(os.path.join(root, "it-pick.json"), "w").write(head[:-1] + ',"pickProbes":[\n  ' + rows + "\n]}\n")
print("it-static, it-runtime, it-extra, it-pick")
