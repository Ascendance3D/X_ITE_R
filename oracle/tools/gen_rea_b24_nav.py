#!/usr/bin/env python3
"""REA batch 24 (issue #91) navigation cases that the batch 09 set (gen_rea_b09_nav.py) does not have:
collision against a ceiling, the step-up threshold, avatarSize variants (radius, height, stepHeight), NavigationInfo speed,
EXAMINE around a Viewpoint centerOfRotation, and WALK inside a tilted Transform. Worlds are written to
oracle/synthetic-rea-b24-nav/*.wrl and stepped scripts to oracle/synthetic-rea-b24-nav/scripts/*.json (512x512, dt = 1/30,
pointer y measured from the bottom, same script format as batch 09). Authored from the X_ITE 16.5.0 navigation source only.

  python3 -I oracle/tools/gen_rea_b24_nav.py
"""
import json, math, os

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "synthetic-rea-b24-nav"))
os.makedirs(os.path.join(root, "scripts"), exist_ok=True)
cases = []
HEADER = "#VRML V2.0 utf8\n# REA batch 24 navigation oracle world (generated by oracle/tools/gen_rea_b24_nav.py).\n"


def box(cx, cy, cz, sx, sy, sz, color="0.6 0.6 0.6"):
    return (f"Transform {{ translation {cx} {cy} {cz} children Shape {{ appearance Appearance {{ material Material {{ diffuseColor {color} }} }} "
            f"geometry Box {{ size {sx} {sy} {sz} }} }} }}")


FLOOR = box(0, -0.1, 0, 40, 0.2, 40, "0.4 0.4 0.4")
LANDMARKS = "\n".join([box(3, 0.5, 2, 1, 1, 1, "0.9 0.9 0.2"), box(-6, 1.0, 9, 1, 2, 1, "0.2 0.9 0.9"), box(0, 2.5, -9, 6, 0.4, 0.4, "0.9 0.2 0.9")])


def nav(kind, size="0.25 1.6 0.75", speed=4):
    return f'NavigationInfo {{ type [ "{kind}" ] avatarSize [ {size} ] speed {speed} }}'


def vp(pos, desc, extra=""):
    return f'Viewpoint {{ position {pos} {extra} description "{desc}" }}'


def world(name, navinfo, viewpoints, body):
    open(os.path.join(root, name + ".wrl"), "w").write(HEADER + navinfo + "\n" + "\n".join(viewpoints) + "\n" + body + "\n")


def script(name, frames, events, capture, probes=None):
    d = {"size": [512, 512], "t0": 946684800, "dt": 1 / 30, "capture": capture, "dump": [], "frames": frames,
         "events": sorted(events, key=lambda e: e["frame"])}
    if probes:
        d["collisionProbes"] = probes
    json.dump(d, open(os.path.join(root, "scripts", name + ".json"), "w"), indent=1)


def case(name, w, s=None):
    cases.append((name, w if "/" in w else "oracle/synthetic-rea-b24-nav/" + w + ".wrl", s or name))


def hold(button, start, to, frames, f0=2):
    return [{"frame": f0, "type": "mousedown", "button": button, "x": start[0], "y": start[1]},
            {"frame": f0 + 1, "type": "mousemove", "x": to[0], "y": to[1]},
            {"frame": f0 + 1 + frames, "type": "mouseup", "button": button, "x": to[0], "y": to[1]}]


def drag(button, start, pts, f0=2, end_extra=0):
    ev = [{"frame": f0, "type": "mousedown", "button": button, "x": start[0], "y": start[1]}]
    f = f0 + 1
    for p in pts:
        ev.append({"frame": f, "type": "mousemove", "x": p[0], "y": p[1]})
        f += 1
    ev.append({"frame": f + end_extra, "type": "mouseup", "button": button, "x": pts[-1][0], "y": pts[-1][1]})
    return ev, f + end_extra


def wheel(frames, delta, x=256, y=256):
    return [{"frame": f, "type": "wheel", "deltaY": delta, "x": x, "y": y} for f in frames]


def key(frame, k):
    return {"frame": frame, "type": "key", "key": k}


def mods(frame, shift=False, ctrl=False, alt=False):
    return {"frame": frame, "type": "mods", "shift": shift, "ctrl": ctrl, "alt": alt}


def probe_directions():
    out = []
    for el in (-60, -30, 0, 30, 60):
        for az in range(0, 360, 45):
            a, e = math.radians(az), math.radians(el)
            out.append([round(math.cos(e) * math.sin(a), 6), round(math.sin(e), 6), round(-math.cos(e) * math.cos(a), 6)])
    return out + [[0, -1, 0], [0, 1, 0], [0.3, -1, 0.1], [-0.2, -1, -0.3]]


C = (256, 256)
FWD0 = (256, 330)  # the pointer offset of the batch 09 WALK / FLY cases (74 px below the center: forward)
FWD = (256, 400)  # 144 px: about 4 units per second at speed 4
PROBES = probe_directions()

# --- ceiling: the collision volume reaches radius (0.25) above the eye ---------------------------------------------
# beam bottoms at 1.7 (inside the volume, eye 1.6 + 0.25 = 1.85) and 2.0 (above it)
world("nav-ceiling", nav("WALK"), [vp("-2 1.6 12", "low beam"), vp("2 1.6 12", "high beam")],
      FLOOR + "\nCollision { collide TRUE children [\n" + box(-2, 1.9, 4, 3, 0.4, 1, "0.8 0.3 0.3") + "\n" + box(2, 2.2, 4, 3, 0.4, 1, "0.3 0.8 0.3") + "\n] }\n" + LANDMARKS)
script("walk-ceiling-block", 130, hold(0, C, FWD, 100), [20, 50, 80, 130], PROBES)
case("walk-ceiling-block", "nav-ceiling")
script("walk-ceiling-pass", 170, [key(3, "PageDown")] + hold(0, C, FWD, 100, f0=40), [35, 70, 100, 140, 170], PROBES)
case("walk-ceiling-pass", "nav-ceiling")

# --- step-up threshold (stepHeight 0.75): a 0.7 high block is climbed, a 0.8 high block is a wall --------------------
world("nav-step", nav("WALK"), [vp("-3 1.6 12", "step 0.7"), vp("3 1.6 12", "step 0.8")],
      FLOOR + "\nCollision { collide TRUE children [\n" + box(-3, 0.35, 4, 3, 0.7, 2, "0.7 0.5 0.3") + "\n" + box(3, 0.4, 4, 3, 0.8, 2, "0.7 0.5 0.3") + "\n] }\n" + LANDMARKS)
script("walk-step-below-limit", 130, hold(0, C, FWD, 100), [30, 60, 90, 130], PROBES)
case("walk-step-below-limit", "nav-step")
script("walk-step-above-limit", 170, [key(3, "PageDown")] + hold(0, C, FWD, 100, f0=40), [35, 70, 100, 140, 170], PROBES)
case("walk-step-above-limit", "nav-step")

# --- stepHeight 0: even a 0.1 high curb stops the avatar -----------------------------------------------------------
world("nav-step-zero", nav("WALK", "0.25 1.6 0"), [vp("0 1.6 12", "start")],
      FLOOR + "\nCollision { collide TRUE children [\n" + box(0, 0.05, 4, 6, 0.1, 2, "0.7 0.5 0.3") + "\n] }\n" + LANDMARKS)
script("walk-step-zero", 110, hold(0, C, FWD, 90), [30, 60, 110], PROBES)
case("walk-step-zero", "nav-step-zero")

# --- stepHeight 3 (larger than avatarHeight 1.6): the collision volume bottom is limited to -radius -----------------
world("nav-step-large", nav("WALK", "0.25 1.6 3"), [vp("0 1.6 12", "start")],
      FLOOR + "\nCollision { collide TRUE children [\n" + box(0, 0.5, 4, 6, 1.0, 2, "0.7 0.5 0.3") + "\n" + box(0, 1.5, -2, 6, 3.0, 1, "0.8 0.3 0.3") + "\n] }\n" + LANDMARKS)
script("walk-step-large", 190, hold(0, C, FWD, 170), [30, 70, 110, 150, 190], PROBES)
case("walk-step-large", "nav-step-large")

# --- avatarHeight 3: falls to 3 above the floor, steps up when less than stepHeight below (2.5), stays when more (1) -----------
world("nav-tall", nav("WALK", "0.25 3 0.75"), [vp("0 2.5 12", "pop"), vp("0 1 12", "low"), vp("0 6 12", "fall")], FLOOR + "\n" + LANDMARKS)
script("walk-tall-fall", 100, [key(3, "PageDown"), key(4, "PageDown")], [5, 15, 30, 50, 100])
case("walk-tall-fall", "nav-tall")
script("walk-tall-pop", 80, [], [1, 2, 3, 5, 10, 40, 80])
case("walk-tall-pop", "nav-tall")
script("walk-tall-low", 80, [key(3, "PageDown")], [5, 10, 40, 80])
case("walk-tall-low", "nav-tall")

# --- collision radius 0 and 1 -------------------------------------------------------------------------------------
wall = "Collision { collide TRUE children [\n" + box(0, 1.5, 4, 8, 3, 0.4, "0.8 0.3 0.3") + "\n] }\n"
world("nav-radius-zero", nav("WALK", "0 1.6 0.75"), [vp("0 1.6 12", "start")], FLOOR + "\n" + wall + LANDMARKS)
script("walk-radius-zero", 110, hold(0, C, FWD, 90), [30, 60, 110], PROBES)
case("walk-radius-zero", "nav-radius-zero")
world("nav-radius-large", nav("WALK", "1 1.6 0.75"), [vp("0 1.6 12", "start")], FLOOR + "\n" + wall + LANDMARKS)
script("walk-radius-large", 110, hold(0, C, FWD, 90), [30, 60, 110], PROBES)
case("walk-radius-large", "nav-radius-large")

# --- NavigationInfo speed ------------------------------------------------------------------------------------------
for s in (0, 1, 16):
    world(f"nav-speed-{s}", nav("WALK", speed=s), [vp("0 1.6 12", "start")], FLOOR + "\n" + wall + LANDMARKS)
    script(f"walk-speed-{s}", 90, hold(0, C, FWD0, 70), [20, 50, 90])
    case(f"walk-speed-{s}", f"nav-speed-{s}")
world("nav-speed-fly-1", nav("FLY", speed=1), [vp("0 1.6 12", "start")], FLOOR + "\n" + wall + LANDMARKS)
script("fly-speed-1-shift", 90, [mods(1, shift=True)] + hold(0, C, FWD0, 70), [20, 50, 90])
case("fly-speed-1-shift", "nav-speed-fly-1")

# --- EXAMINE around Viewpoint.centerOfRotation ---------------------------------------------------------------------
world("nav-examine-cor", 'NavigationInfo { type [ "EXAMINE" ] }',
      ['Viewpoint { position 0 0 12 centerOfRotation 3 1 0 description "offset center" }'],
      box(3, 1, 0, 1.5, 1.5, 1.5, "0.9 0.9 0.2") + "\n" + box(-3, 0, -2, 1, 3, 1, "0.2 0.9 0.9") + "\n" + box(0, -2, 0, 12, 0.2, 8, "0.5 0.5 0.5"))
ev, last = drag(0, C, [(256 + 8 * i, 256 + 5 * i) for i in range(1, 14)], end_extra=20)
script("examine-cor-rotate", last + 30, ev, [8, last + 20, last + 30])
case("examine-cor-rotate", "nav-examine-cor")
script("examine-cor-wheel", 70, wheel(range(2, 10), -100) + wheel(range(30, 38), 100), [6, 20, 45, 70])
case("examine-cor-wheel", "nav-examine-cor")
ev, last = drag(1, C, [(256 + 8 * i, 256 - 6 * i) for i in range(1, 14)], end_extra=20)
script("examine-cor-pan", last + 40, ev + wheel(range(last + 25, last + 30), -100), [8, last + 20, last + 40])
case("examine-cor-pan", "nav-examine-cor")
ev, last = drag(0, C, [(256 + 8 * i, 256 + 5 * i) for i in range(1, 14)], end_extra=0)
script("examine-cor-spin", last + 80, ev, [last + 1, last + 20, last + 80])
case("examine-cor-spin", "nav-examine-cor")

# --- WALK inside a tilted Transform: the up vector is the Viewpoint's local y axis ----------------------------------
tilt = ("Transform { rotation 0 0 1 0.3 children [\n" + vp("0 1.6 12", "tilted start") + "\n" + vp("0 6 12", "tilted high") + "\n" + FLOOR + "\nCollision { collide TRUE children [\n"
        + box(0, 1.5, -2, 8, 3, 0.4, "0.8 0.3 0.3") + "\n] }\n" + LANDMARKS + "\n] }")
world("nav-tilted", nav("WALK"), [], tilt)
script("walk-tilted-forward", 120, hold(0, C, FWD, 100), [20, 50, 80, 120], PROBES)
case("walk-tilted-forward", "nav-tilted")
script("walk-tilted-fall", 80, [key(3, "PageDown")], [5, 15, 30, 50, 80])
case("walk-tilted-fall", "nav-tilted")

# --- more EXAMINE items ---------------------------------------------------------------------------------------------
B09 = "oracle/synthetic-rea-b09-nav/"
ev, last = drag(0, C, [(256 + 8 * i, 256 + 5 * i) for i in range(1, 14)], end_extra=0)
script("examine-spin-wheel", last + 60, ev + wheel(range(last + 10, last + 14), -100), [last + 1, last + 9, last + 14, last + 30, last + 60])
case("examine-spin-wheel", B09 + "nav-examine.wrl")  # a wheel step removes the spin

ORTHO_HEADER = "#X3D V3.3 utf8\nPROFILE Immersive\nCOMPONENT Navigation:3\n# REA batch 24 navigation oracle world (generated by oracle/tools/gen_rea_b24_nav.py).\n"
ortho_body = box(0, 0, 0, 2, 2, 2, "0.9 0.9 0.2") + "\n" + box(-3, 1, -3, 1, 3, 1, "0.2 0.9 0.9") + "\n" + box(2, -1, -4, 4, 0.2, 4, "0.5 0.5 0.5")
open(os.path.join(root, "nav-examine-ortho.wrl"), "w").write(
    ORTHO_HEADER + 'NavigationInfo { type [ "EXAMINE" ] }\nOrthoViewpoint { position 0 0 12 fieldOfView [ -5 -5 5 5 ] description "ortho" }\n' + ortho_body + "\n")
ev, last = drag(1, C, [(256 + 8 * i, 256 - 6 * i) for i in range(1, 14)], end_extra=20)
script("examine-ortho-pan", last + 20, ev, [8, last + 20])
case("examine-ortho-pan", "nav-examine-ortho")
ev, last = drag(0, C, [(256 + 8 * i, 256 + 5 * i) for i in range(1, 14)], end_extra=20)
script("examine-ortho-rotate-wheel", last + 70, ev + wheel(range(last + 25, last + 33), -100), [8, last + 20, last + 50, last + 70])
case("examine-ortho-rotate-wheel", "nav-examine-ortho")


def option_world(name, kind, option, value, size="0.25 1.6 0.75", speed=4, viewpoints=None, body=None):
    """A world whose Script sets one browser option in initialize (SAI Browser.setBrowserOption)."""
    text = ("#X3D V4.0 utf8\nPROFILE Immersive\nCOMPONENT Scripting:1\n# REA batch 24 navigation oracle world (generated by oracle/tools/gen_rea_b24_nav.py).\n"
            + nav(kind, size, speed) + "\n" + "\n".join(viewpoints or [vp("0 1.6 12", "start")]) + "\n" + (body if body is not None else FLOOR + "\n" + LANDMARKS) + "\n"
            + f'Script {{ url "ecmascript:\\nfunction initialize () {{ Browser .setBrowserOption (\'{option}\', {value}); }}\\n" }}\n')
    open(os.path.join(root, name + ".wrl"), "w").write(text.replace("\\n", "\n"))


# StraightenHorizon false: the trackball rotation of EXAMINE, and the look around of FLY (WALK always straightens)
option_world("nav-examine-trackball", "EXAMINE", "StraightenHorizon", "false", viewpoints=[vp("0 0 12", "start")], body=box(3, 1, 0, 1.5, 1.5, 1.5, "0.9 0.9 0.2") + "\n" + box(-3, 0, -2, 1, 3, 1, "0.2 0.9 0.9"))
ev, last = drag(0, C, [(256 + 8 * i, 256 + 5 * i) for i in range(1, 14)], end_extra=0)
script("examine-trackball-spin", last + 80, ev, [last + 1, last + 20, last + 80])
case("examine-trackball-spin", "nav-examine-trackball")
ev, last = drag(0, C, [(256, 256 + 25 * i) for i in range(1, 12)], end_extra=40)
script("examine-trackball-pole", last + 40, ev, [6, last + 1, last + 40])
case("examine-trackball-pole", "nav-examine-trackball")
for t in ("fly", "walk"):
    option_world(f"nav-{t}-trackball", t.upper(), "StraightenHorizon", "false")
    ev, last = drag(0, C, [(256 + 12 * i, 256 + 10 * i) for i in range(1, 16)], end_extra=20)
    script(f"{t}-turn-no-straighten", last + 20, ev, [8, 20, last + 20])
    case(f"{t}-turn-no-straighten", f"nav-{t}-trackball")
ev, last = drag(0, C, [(256 + 10 * i, 256 - 7 * i) for i in range(1, 14)], f0=3, end_extra=30)
script("fly-ctrl-look-no-straighten", last + 20, [mods(2, ctrl=True)] + ev + [mods(last + 2)], [8, 18, last + 20])
case("fly-ctrl-look-no-straighten", "nav-fly-trackball")

# --- PLANE: zoom-in minimum (fieldOfViewScale >= 0.00001, 225 wheel steps) and the double click look at ------------------
script("plane-zoom-in-limit", 240, wheel(range(1, 231), -100, 300, 200), [100, 200, 230, 240])
case("plane-zoom-in-limit", B09 + "nav-plane.wrl")
script("plane-dblclick", 80, [{"frame": 2, "type": "dblclick", "x": 441, "y": 188}], [10, 40, 80])
case("plane-dblclick", B09 + "nav-plane.wrl")
script("plane-dblclick-alt", 80, [mods(1, alt=True), {"frame": 2, "type": "dblclick", "x": 441, "y": 188}, mods(40)], [10, 40, 80])
case("plane-dblclick-alt", B09 + "nav-plane.wrl")

# --- LOOKAT around a Viewpoint centerOfRotation ----------------------------------------------------------------------
world("nav-lookat-cor", 'NavigationInfo { type [ "LOOKAT" ] }', ['Viewpoint { position 0 0 12 centerOfRotation 3 1 0 description "offset center" }'],
      box(3, 1, 0, 1.5, 1.5, 1.5, "0.9 0.9 0.2") + "\n" + box(-3, 0, -2, 1, 3, 1, "0.2 0.9 0.9"))
script("lookat-cor-wheel", 70, wheel(range(2, 10), -100) + wheel(range(30, 38), 100), [6, 20, 45, 70])
case("lookat-cor-wheel", "nav-lookat-cor")
ev, last = drag(0, C, [(256 + 8 * i, 256 + 5 * i) for i in range(1, 14)], end_extra=30)
script("lookat-cor-drag", last + 40, ev + wheel(range(last + 3, last + 6), -100), [8, last + 30, last + 40])
case("lookat-cor-drag", "nav-lookat-cor")

# --- gravity option (Browser.setBrowserOption ('Gravity', g)) and avatarSize defaults -------------------------------------
for g in (20, 0):
    option_world(f"nav-gravity-{g}", "WALK", "Gravity", str(g), viewpoints=[vp("0 6 12", "high")])
    script(f"walk-fall-gravity-{g}", 80, [], [5, 10, 20, 30, 50, 80])
    case(f"walk-fall-gravity-{g}", f"nav-gravity-{g}")
for tag, size in (("short", "0.5"), ("empty", ""), ("negative", "-1 -1 -1")):
    world(f"nav-avatar-{tag}", nav("WALK", size), [vp("0 4 12", "high")], FLOOR + "\n" + wall + LANDMARKS)
    script(f"walk-avatar-size-{tag}", 130, hold(0, C, FWD, 100, f0=40), [10, 35, 60, 100, 130])
    case(f"walk-avatar-size-{tag}", f"nav-avatar-{tag}")

# FLY look around (ctrl + left drag) past the vertical: X3DFlyViewer.addRotation ignores a rotation whose up component exceeds CRITICAL_ANGLE (0.99)
ev, f = [mods(1, ctrl=True)], 2
for _ in range(4):
    e, last = drag(0, C, [(256, 256 - 24 * i) for i in range(1, 11)], f0=f, end_extra=2)
    ev += e
    f = last + 2
script("fly-ctrl-look-pole", f + 20, ev + [mods(f)], [12, 30, 50, f + 20])
case("fly-ctrl-look-pole", B09 + "nav-fly.wrl")

with open(os.path.join(root, "cases.txt"), "w") as f:
    for name, w, s in cases:
        f.write(f"{name} {w} oracle/synthetic-rea-b24-nav/scripts/{s}.json\n")
print(len(cases), "cases")
