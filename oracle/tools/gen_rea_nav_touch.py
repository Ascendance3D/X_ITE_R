#!/usr/bin/env python3
"""sub:nav.walk-fly (F16): one-finger drive and two-finger look around of the WALK and FLY viewers, against pinned X_ITE 16.5.0.

  python3 -I -B oracle/tools/gen_rea_nav_touch.py

Writes oracle/synthetic-rea-nav-touch/{walk,walk-nograv,fly}.wrl, scripts/*.json and cases.txt (`name world script msaa`). New files only.
The touch events are those of oracle/tools/gen_rea_pointer_touch.py (origin bottom left, whole pixels; `touchstart` / `touchmove` with
"points", `touchend` with "ids", `touchcancel`). Every frame is captured (the viewpoint pose) and dumped (the scene text, whose Script
string `hist` lists the TouchSensor events and the ProximitySensor activity). Clean-room: written for this test.
"""
import json, os

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
d = os.path.join(root, "oracle", "synthetic-rea-nav-touch")
DT = 1 / 30
C = (256, 256)
TS = (102, 256)  # the TouchSensor box, left of the way ahead


def world(kind):
    nav = '"FLY" "ANY"' if kind == "fly" else '"WALK" "ANY"'
    grav = "\nScript { url \"ecmascript:\nfunction initialize () { Browser .setBrowserOption ('Gravity', 0); }\n\" }" if kind == "walk-nograv" else ""
    return f"""#X3D V4.0 utf8
PROFILE Immersive
COMPONENT Scripting:1
# Synthetic world (generated by oracle/tools/gen_rea_nav_touch.py). Touch navigation of WALK and FLY.
NavigationInfo {{ type [ {nav} ] avatarSize [ 0.25 1.6 0.75 ] speed 4 }}
Viewpoint {{ position 0 3 12 description "start" }}{grav}
DEF PX ProximitySensor {{ size 1000 1000 1000 }}
Transform {{ translation 0 -0.1 0 children Shape {{ appearance Appearance {{ material Material {{ diffuseColor 0.4 0.4 0.4 }} }} geometry Box {{ size 60 0.2 60 }} }} }}
Transform {{ translation 0 0.25 10 children Shape {{ appearance Appearance {{ material Material {{ diffuseColor 0.3 0.3 0.9 }} }} geometry Box {{ size 3 0.5 1 }} }} }}
Transform {{ translation 0 2 7 children Shape {{ appearance Appearance {{ material Material {{ diffuseColor 0.9 0.3 0.2 }} }} geometry Box {{ size 2 4 0.5 }} }} }}
Transform {{ translation -1.5 1.6 6 children [ DEF TS TouchSensor {{ }} Shape {{ appearance Appearance {{ material Material {{ diffuseColor 0.2 0.8 0.3 }} }} geometry Box {{ size 1.5 1.5 1.5 }} }} ] }}
DEF LOG Script {{
  inputOutput SFString hist ""
  inputOnly SFBool TS_isActive
  inputOnly SFBool TS_isOver
  inputOnly SFTime TS_touchTime
  inputOnly SFBool PX_isActive
  inputOnly SFVec3f PX_position
  url "ecmascript:
    var n = 0;
    function TS_isActive (v) {{ hist = hist + ' TS_isActive=' + v; }}
    function TS_isOver (v) {{ hist = hist + ' TS_isOver=' + v; }}
    function TS_touchTime (v) {{ hist = hist + ' TS_touchTime'; }}
    function PX_isActive (v) {{ hist = hist + ' PX_isActive=' + v; }}
    function PX_position (v) {{ n = n + 1; hist = hist .replace (/ PX_n=\\\\d+$/, '') + ' PX_n=' + n; }}
  "
}}
ROUTE TS.isActive TO LOG.TS_isActive
ROUTE TS.isOver TO LOG.TS_isOver
ROUTE TS.touchTime TO LOG.TS_touchTime
ROUTE PX.isActive TO LOG.PX_isActive
ROUTE PX.position_changed TO LOG.PX_position
"""


class S:
    def __init__(self, frames):
        self.ev, self.frames = [], frames

    def add(self, frame, kind, *points, ids=None):
        e = {"frame": frame, "type": kind}
        if kind in ("touchstart", "touchmove"):
            e["points"] = [list(p) for p in points]
        elif kind == "touchend" and ids is not None:
            e["ids"] = ids
        self.ev.append(e)

    def json(self):
        r = list(range(1, self.frames + 1))
        return {"size": [512, 512], "t0": 946684800, "dt": DT, "capture": r, "dump": r, "frames": self.frames, "events": self.ev}


def off(p, dx, dy):
    return (p[0] + dx, p[1] + dy)


cases = {}

# One finger held away from where it went down: forward (up), back, turn, a diagonal; the hold reaches the wall.
# (a low box at z 10 is stepped onto with gravity; the wall at z 7 blocks)
s = S(90)
s.add(2, "touchstart", C)
s.add(3, "touchmove", off(C, 0, 60))
s.add(4, "touchmove", off(C, 0, 100))
s.add(70, "touchend")
s.add(72, "touchstart", C)
s.add(73, "touchmove", off(C, 0, -70))
s.add(86, "touchend")
cases["drive-forward-back"] = s

s = S(70)
s.add(2, "touchstart", C)
s.add(3, "touchmove", off(C, 90, 0))
s.add(25, "touchend")
s.add(28, "touchstart", C)
s.add(29, "touchmove", off(C, -60, 80))
s.add(55, "touchend")
cases["drive-turn-diagonal"] = s

# Two fingers look around (the middle moves), the second finger added and removed.
s = S(60)
A = [(226, 256), (286, 256)]
s.add(2, "touchstart", A[0])
s.add(3, "touchstart", *A)
for i in range(1, 6):
    s.add(3 + i, "touchmove", off(A[0], 6 * i, 4 * i), off(A[1], 6 * i, 4 * i))
for i in range(1, 6):
    s.add(8 + i, "touchmove", off(A[0], 30 - 8 * i, 20 + 5 * i), off(A[1], 30 - 8 * i, 20 + 5 * i))
s.add(16, "touchend", ids=[1])
s.add(17, "touchmove", off(A[0], -10, 45))
s.add(18, "touchmove", off(A[0], -20, 50))
s.add(20, "touchend")
cases["look-around"] = s

# One finger drives, a second finger turns it into a look around, the second finger lifts, the first drives again (touchmove with no
# press), then both are down at once and a third finger ends the look around.
s = S(90)
s.add(2, "touchstart", C)
s.add(3, "touchmove", off(C, 0, 80))
s.add(20, "touchstart", off(C, 0, 80), off(C, 60, 80))
for i in range(1, 5):
    s.add(20 + i, "touchmove", off(C, 5 * i, 80), off(C, 60 + 5 * i, 80 + 4 * i))
s.add(26, "touchend", ids=[1])
for i in range(1, 5):
    s.add(26 + i, "touchmove", off(C, 20, 80 + 10 * i))
s.add(32, "touchend")
s.add(40, "touchstart", C)
s.add(41, "touchmove", off(C, 40, 90))
s.add(49, "touchstart", off(C, 40, 90), off(C, 100, 90))
s.add(50, "touchstart", off(C, 40, 90), off(C, 100, 90), off(C, 70, 20))
s.add(52, "touchmove", off(C, 40, 90), off(C, 100, 90), off(C, 70, 40))
s.add(54, "touchmove", off(C, 40, 90))
s.add(56, "touchend", ids=[2])
s.add(57, "touchend", ids=[1])
s.add(58, "touchend")
cases["one-two-one"] = s

# The touch ends while moving, and a new touch starts at once (and the same with the touches lifted one after the other).
s = S(70)
s.add(2, "touchstart", C)
s.add(3, "touchmove", off(C, -40, 70))
s.add(15, "touchend")
s.add(16, "touchstart", off(C, 100, 100))
s.add(17, "touchmove", off(C, 100, 30))
s.add(30, "touchend")
s.add(33, "touchstart", C)
s.add(34, "touchstart", C, off(C, 50, 0))
s.add(35, "touchmove", off(C, 8, 8), off(C, 58, 8))
s.add(37, "touchend", ids=[0])
s.add(39, "touchend")
cases["end-during-move"] = s

# touchcancel while moving and while looking around: X_ITE's viewers have no touchcancel handler (kept difference, ADR 0001 row 1).
s = S(70)
s.add(2, "touchstart", C)
s.add(3, "touchmove", off(C, 0, 80))
s.add(20, "touchcancel")
s.add(29, "touchstart", C)
s.add(30, "touchstart", C, off(C, 60, 0))
s.add(31, "touchmove", off(C, 10, 10), off(C, 70, 10))
s.add(36, "touchend", ids=[1])
s.add(37, "touchcancel")
s.add(44, "touchstart", C)
s.add(45, "touchmove", off(C, 0, 40))
s.add(52, "touchend")
cases["cancel-during-move"] = s

# A finger down on a TouchSensor presses it and does not drive; a finger that moves onto it keeps driving; the sensor press and a
# second finger.
s = S(80)
s.add(2, "touchstart", TS)
s.add(3, "touchmove", off(TS, 0, 70))
s.add(20, "touchend")
s.add(24, "touchstart", C)
s.add(25, "touchmove", off(C, -100, 60))
s.add(35, "touchmove", off(TS, 0, 0))
s.add(45, "touchend")
s.add(50, "touchstart", TS)
s.add(53, "touchstart", TS, off(TS, 60, 0))
s.add(54, "touchmove", TS, off(TS, 70, 10))
s.add(57, "touchend", ids=[1])
s.add(58, "touchend")
cases["on-sensor"] = s

# Pitch down with two fingers, then drive forward: FLY descends to the floor (collision), WALK keeps its height.
s = S(80)
s.add(2, "touchstart", off(C, -30, 0))
s.add(3, "touchstart", off(C, -30, 0), off(C, 30, 0))
for i in range(1, 6):
    s.add(3 + i, "touchmove", off(C, -30, -12 * i), off(C, 30, -12 * i))
s.add(10, "touchend", ids=[1])
s.add(11, "touchend")
s.add(14, "touchstart", C)
s.add(15, "touchmove", off(C, 0, 60))
s.add(60, "touchend")
cases["pitch-then-drive"] = s

os.makedirs(os.path.join(d, "scripts"), exist_ok=True)
lines = []
for kind in ("walk", "walk-nograv", "fly"):
    open(os.path.join(d, kind + ".wrl"), "w").write(world(kind))
    for name, sc in cases.items():
        full = f"{kind}-{name}"
        json.dump(sc.json(), open(os.path.join(d, "scripts", full + ".json"), "w"), indent=1)
        lines.append(f"{full} oracle/synthetic-rea-nav-touch/{kind}.wrl oracle/synthetic-rea-nav-touch/scripts/{full}.json 0")
open(os.path.join(d, "cases.txt"), "w").write("\n".join(lines) + "\n")
print(len(lines), "cases")
