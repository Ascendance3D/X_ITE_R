#!/usr/bin/env python3
"""REA ledger node:Collision / node:Anchor: Collision isActive / collideTime event order for a WALK avatar, and Billboard
orientation in the COLLISION, DISPLAY and PICKING passes while the viewpoint moves (oracle/synthetic-rea-collision-time).
Authored from the X_ITE 16.5.0 source only (Collision.js, Billboard.js, X3DRenderObject.collide). 512x512, dt = 1/30, pointer
y measured from the bottom, same script format as batch 24 (oracle/tools/gen_rea_b24_nav.py).

  ct-wall       one Collision around a wall: walk into it, back off, walk into it again (isActive TRUE / FALSE / TRUE,
                collideTime at each TRUE)
  ct-disabled   enabled FALSE: the avatar walks through, no event
  ct-invisible  visible FALSE: not collidable either (the avatar walks through)
  ct-proxy      proxy: only the proxy is collidable, the visible child is not
  ct-nested     Collision in Collision around one wall: both become active, in outer-to-inner order
  ct-graze      two walls beside the avatar's path, 0.30 (inside collisionRadius * sqrt 2 = 0.3536) and 0.40 (outside)
  ct-edge       two walls beside the path, 0.345 and 0.362, either side of the 0.3536 threshold
  ct-bb-*       a flat panel under Billboard (axisOfRotation 0 1 0 `y` or 0 0 0 `f`) in Collision > Billboard (`cb`),
                Billboard > Collision (`bc`), Anchor > Billboard (`ab`) or Collision > Anchor > Billboard (`cab`), walked
                at from an oblique start; PageDown binds a second Viewpoint and the walk repeats. Billboard.traverse
                (COLLISION) rotates towards the collision camera, the DISPLAY pass towards the viewer.
  ct-bb-ctl     the same with a Group instead of the Billboard (control)
  ct-*-pick     ct-wall, ct-nested and ct-bb-ctl again, with pickProbes (the hit point 0.27 to 0.38 from the surface)
  ct-bb-head-*  Collision > Billboard (y, f) or Group (ctl) with the panel centered on the first walk's line
  ct-live-inline   the wall Collision is inside an Inline (ct-live-inline-inner.wrl, IMPORTed as C1 so that the parent Script logs its
                   isActive and collideTime); the avatar walks into it and keeps pushing, the parent Script sets the Inline's `load`
                   FALSE (at 2.6 s of page time, the avatar stopped against the wall since frame 59), then TRUE (4.3 s; hist keeps time stamps only: the Script's prepareEvents count depends on when the Inline finished loading), and the avatar walks back at the wall from behind. Collision.set_live__
                   (removeCollision / addCollision) and what happens to isActive on unload. Script key "settle" (loads at run time).
  ct-live-inline-two  the same with a second, never reached Collision C0 in the parent (the browser's collision count stays above 0 while
                   the Inline is unloaded)

Every script has collisionProbes (getClosestObject along 44 directions) and, except where noted, pickProbes (a 16 x 16
pointing-buffer grid, compared bit for bit).

NOTE: ct-wall, ct-nested and ct-bb-ctl end with the avatar 0.27 to 0.38 from a surface that fills the picture. When they were
written, the pointing buffer's hit point of the two renderers was measured to differ there by 3.05e-7 (all 256 probes), so they have
no pickProbes. On the current Rust that no longer reproduces (issue #94 / node:Collision, 2026-11-04): ct-wall-pick, ct-nested-pick and
ct-bb-ctl-pick are the same worlds with the 16 x 16 pickProbes grid, bit for bit equal at MSAA 0 and 4. The three originals and their
recordings are unchanged.

  python3 -I -B oracle/tools/gen_rea_collision_time.py
"""
import json, math, os

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "synthetic-rea-collision-time"))
os.makedirs(os.path.join(root, "scripts"), exist_ok=True)
cases = []
HEADER = ("#X3D V4.0 utf8\nPROFILE Full\nCOMPONENT Scripting:1\n"
          "# REA collision / billboard oracle world (generated by oracle/tools/gen_rea_collision_time.py).\n")
SIZE = 512
T0 = 946684800


def mat(c):
    return f"Appearance {{ material Material {{ diffuseColor {c} }} }}"


def box(cx, cy, cz, sx, sy, sz, color="0.6 0.6 0.6"):
    return f"Transform {{ translation {cx} {cy} {cz} children Shape {{ appearance {mat(color)} geometry Box {{ size {sx} {sy} {sz} }} }} }}"


FLOOR = box(0, -0.1, 0, 60, 0.2, 60, "0.4 0.4 0.4")
LANDMARKS = "\n".join([box(5, 0.5, 6, 1, 1, 1, "0.9 0.9 0.2"), box(-6, 1.0, 9, 1, 2, 1, "0.2 0.9 0.9"), box(0, 2.5, -9, 6, 0.4, 0.4, "0.9 0.2 0.9")])
NAV = 'NavigationInfo { type [ "WALK" ] avatarSize [ 0.25 1.6 0.75 ] speed 4 transitionType [ "TELEPORT" ] }'


def vp(pos, desc, extra=""):
    return f'Viewpoint {{ position {pos} {extra} description "{desc}" }}'


def logger(names):
    """A Script that appends every Collision's isActive and collideTime (with the event timestamp) to `hist`."""
    if not names:
        return ""
    fields, funcs, routes = "", "", ""
    for n in names:
        fields += f"  inputOnly SFBool {n}_a\n  inputOnly SFTime {n}_t\n"
        funcs += (f"    function {n}_a (v, t) {{ hist = hist + ' ' + frame + ':{n}.isActive=' + v + '@' + (t - {T0}) .toFixed (6); }}\n"
                  f"    function {n}_t (v, t) {{ hist = hist + ' ' + frame + ':{n}.collideTime=' + (v - {T0}) .toFixed (6); }}\n")
        routes += f"ROUTE {n}.isActive TO LOG.{n}_a\nROUTE {n}.collideTime TO LOG.{n}_t\n"
    return ("DEF LOG Script {\n  inputOutput SFString hist \"\"\n  inputOutput SFInt32 frame 0\n" + fields + "  url \"ecmascript:\n" + funcs
            + "    function prepareEvents () { frame = frame + 1; }\n\"\n}\n" + routes)


def probe_directions():
    out = []
    for el in (-60, -30, 0, 30, 60):
        for az in range(0, 360, 45):
            a, e = math.radians(az), math.radians(el)
            out.append([round(math.cos(e) * math.sin(a), 6), round(math.sin(e), 6), round(-math.cos(e) * math.cos(a), 6)])
    return out + [[0, -1, 0], [0, 1, 0], [0.3, -1, 0.1], [-0.2, -1, -0.3]]


def pick_grid(step=32, off=16):
    n = (SIZE - off) // step + 1
    return [[off + i * step, off + j * step] for j in range(n) for i in range(n)]


PROBES = probe_directions()
GRID = pick_grid()


def world(name, body, viewpoints, names):
    open(os.path.join(root, name + ".wrl"), "w").write(HEADER + NAV + "\n" + "\n".join(viewpoints) + "\n" + body + "\n" + logger(names))


def script(name, frames, events, capture, pick=True):
    d = {"size": [SIZE, SIZE], "t0": T0, "dt": 1 / 30, "capture": capture, "dump": capture, "frames": frames,
         "events": sorted(events, key=lambda e: e["frame"]), "collisionProbes": PROBES}
    if pick:
        d["pickProbes"] = GRID
    json.dump(d, open(os.path.join(root, "scripts", name + ".json"), "w"), indent=1)


def case(name):
    cases.append((name, f"oracle/synthetic-rea-collision-time/{name}.wrl", f"oracle/synthetic-rea-collision-time/scripts/{name}.json"))


C = (256, 256)
FWD = (256, 400)  # about 4 units per second at speed 4
BACK = (256, 112)


def hold(to, f0, frames, start=C):
    return [{"frame": f0, "type": "mousedown", "button": 0, "x": start[0], "y": start[1]},
            {"frame": f0 + 1, "type": "mousemove", "x": to[0], "y": to[1]},
            {"frame": f0 + 1 + frames, "type": "mouseup", "button": 0, "x": to[0], "y": to[1]}]


def key(frame, k):
    return {"frame": frame, "type": "key", "key": k}


WALL = lambda: box(0, 1.5, 4, 8, 3, 0.4, "0.8 0.3 0.3")
IN_OUT_IN = hold(FWD, 2, 70) + hold(BACK, 80, 40) + hold(FWD, 130, 60)
START = [vp("0 1.6 12", "start")]

# ---- Collision events --------------------------------------------------------------------------------------------------
world("ct-wall", FLOOR + "\nDEF C1 Collision { children [\n" + WALL() + "\n] }\n" + LANDMARKS, START, ["C1"])
script("ct-wall", 200, IN_OUT_IN, [30, 75, 125, 195], pick=False)  # no pickProbes: see NOTE
case("ct-wall")
world("ct-wall-pick", FLOOR + "\nDEF C1 Collision { children [\n" + WALL() + "\n] }\n" + LANDMARKS, START, ["C1"])
script("ct-wall-pick", 200, IN_OUT_IN, [195])
case("ct-wall-pick")

world("ct-disabled", FLOOR + "\nDEF C1 Collision { enabled FALSE children [\n" + WALL() + "\n] }\n" + LANDMARKS, START, ["C1"])
script("ct-disabled", 130, hold(FWD, 2, 120), [30, 75, 130])
case("ct-disabled")

world("ct-invisible", FLOOR + "\nDEF C1 Collision { visible FALSE children [\n" + WALL() + "\n] }\n" + LANDMARKS, START, ["C1"])
script("ct-invisible", 200, IN_OUT_IN, [30, 75, 125, 195])
case("ct-invisible")

proxy = box(0, 1.5, 8, 8, 3, 0.4, "0.3 0.3 0.8")
world("ct-proxy", FLOOR + "\nDEF C1 Collision { proxy " + proxy + " children [\n" + WALL() + "\n] }\n" + LANDMARKS, START, ["C1"])
script("ct-proxy", 200, IN_OUT_IN, [30, 75, 125, 195])
case("ct-proxy")

world("ct-nested", FLOOR + "\nDEF C1 Collision { children [\nDEF C2 Collision { children [\n" + WALL() + "\n] }\nDEF C3 Collision { children [\n"
      + box(0, 1.5, -20, 4, 3, 0.4, "0.3 0.8 0.3") + "\n] }\n] }\n" + LANDMARKS, START, ["C1", "C2", "C3"])
script("ct-nested", 200, IN_OUT_IN, [30, 75, 125, 195], pick=False)
case("ct-nested")
world("ct-nested-pick", FLOOR + "\nDEF C1 Collision { children [\nDEF C2 Collision { children [\n" + WALL() + "\n] }\nDEF C3 Collision { children [\n"
      + box(0, 1.5, -20, 4, 3, 0.4, "0.3 0.8 0.3") + "\n] }\n] }\n" + LANDMARKS, START, ["C1", "C2", "C3"])
script("ct-nested-pick", 200, IN_OUT_IN, [195])
case("ct-nested-pick")


def side_walls(name, left, right):
    body = (FLOOR + f"\nDEF CL Collision {{ children [\n" + box(-left - 0.1, 1.5, 4, 0.2, 3, 4, "0.8 0.3 0.3") + "\n] }\n"
            + f"DEF CR Collision {{ children [\n" + box(right + 0.1, 1.5, 4, 0.2, 3, 4, "0.3 0.8 0.3") + "\n] }\n" + LANDMARKS)
    world(name, body, START, ["CL", "CR"])
    script(name, 130, hold(FWD, 2, 120), [30, 50, 70, 90, 130])
    case(name)


side_walls("ct-graze", 0.30, 0.40)
side_walls("ct-edge", 0.345, 0.362)

# ---- Billboard orientation under Collision / Anchor ------------------------------------------------------------------------
PANEL = box(0, 0, 0, 4, 2, 0.1, "0.9 0.6 0.2")
PANEL_SHAPE = f"Shape {{ appearance {mat('0.9 0.6 0.2')} geometry Box {{ size 4 2 0.1 }} }}"
BB_START = [vp("1.5 1.6 12", "oblique start"), vp("-1.2 1.6 8", "second start")]
# The pointer goes down at the bottom of the picture, away from the panel: an Anchor (a pointing-device sensor) under the pointer would
# take the drag from the viewer.
LOW, LOW_FWD = (256, 40), (256, 184)
BB_WALK = hold(LOW_FWD, 2, 70, LOW) + [key(80, "PageDown")] + hold(LOW_FWD, 84, 60, LOW)


def billboard(kind, axis, x=0.5):
    a = "" if axis is None else f" axisOfRotation {axis}"
    inner = PANEL_SHAPE
    b = f"Billboard {{{a} children [ {inner} ] }}" if axis is not None else f"Group {{ children [ {inner} ] }}"
    wrap = {
        "cb": f"DEF C1 Collision {{ children [ {b} ] }}",
        "bc": (f"Billboard {{{a} children [ DEF C1 Collision {{ children [ {inner} ] }} ] }}" if axis is not None
               else f"Group {{ children [ DEF C1 Collision {{ children [ {inner} ] }} ] }}"),
        "ab": f'Anchor {{ url [ "#" ] description "billboard anchor" children [ {b} ] }}',
        "cab": f'DEF C1 Collision {{ children [ Anchor {{ url [ "#" ] description "billboard anchor" children [ {b} ] }} ] }}',
    }[kind]
    return f"Transform {{ translation {x} 1 3 children [ {wrap} ] }}"


for kind in ("cb", "bc", "ab", "cab"):
    for tag, axis in (("y", "0 1 0"), ("f", "0 0 0")):
        n = f"ct-bb-{kind}-{tag}"
        world(n, FLOOR + "\n" + billboard(kind, axis) + "\n" + LANDMARKS, BB_START, [] if kind == "ab" else ["C1"])
        script(n, 150, BB_WALK, [20, 60, 76, 84, 100, 140])
        case(n)

world("ct-bb-ctl", FLOOR + "\n" + billboard("cb", None) + "\n" + LANDMARKS, BB_START, ["C1"])
script("ct-bb-ctl", 150, BB_WALK, [20, 60, 76, 84, 100, 140], pick=False)
case("ct-bb-ctl")
world("ct-bb-ctl-pick", FLOOR + "\n" + billboard("cb", None) + "\n" + LANDMARKS, BB_START, ["C1"])
script("ct-bb-ctl-pick", 150, BB_WALK, [140])
case("ct-bb-ctl-pick")

# head-on: the panel centered on the first walk's line (x = 1.5)
for n, axis in (("ct-bb-head-y", "0 1 0"), ("ct-bb-head-f", "0 0 0"), ("ct-bb-head-ctl", None)):
    world(n, FLOOR + "\n" + billboard("cb", axis, 1.5) + "\n" + LANDMARKS, BB_START, ["C1"])
    script(n, 150, BB_WALK, [20, 60, 76, 84, 100, 140])
    case(n)

# ---- Collision.set_live__: a Collision inside an Inline that is unloaded and loaded again ------------------------------------
open(os.path.join(root, "ct-live-inline-inner.wrl"), "w").write(
    HEADER + "DEF T1 Transform { translation 0 1.5 4 children [ DEF C1 Collision { children [\n"
    + f"Shape {{ appearance {mat('0.8 0.3 0.3')} geometry Box {{ size 8 3 0.4 }} }}\n] }} ] }}\n"
    # The parent's routes die with the Inline's scene; this Script, inside the Inline, prints what C1 sends while the scene exists
    # (the page console is recorded: script key "console"). No shutdown (): the native build calls it on an unloaded Inline, the pinned page
    # does not (a documented, owner-approved difference, oracle/README.md "Plain Inline reload and abort paths").
    "DEF LOGI Script {\n  inputOnly SFBool a\n  inputOnly SFTime t\n  url \"ecmascript:\n"
    f"    function a (v, ts) {{ print ('inner C1.isActive=' + v + '@' + (ts - {T0}) .toFixed (6)); }}\n"
    f"    function t (v, ts) {{ print ('inner C1.collideTime=' + (v - {T0}) .toFixed (6)); }}\n"
    "\"\n}\n"
    "ROUTE C1.isActive TO LOGI.a\nROUTE C1.collideTime TO LOGI.t\nEXPORT C1\n")


def live_world(name, extra_names):
    names = ["C1"] + extra_names
    fields = "".join(f"  inputOnly SFBool {n}_a\n  inputOnly SFTime {n}_t\n" for n in names)
    funcs = "".join(f"    function {n}_a (v, t) {{ hist = hist + ' ' + '{n}.isActive=' + v + '@' + (t - {T0}) .toFixed (6); }}\n"
                    f"    function {n}_t (v, t) {{ hist = hist + ' ' + '{n}.collideTime=' + (v - {T0}) .toFixed (6); }}\n" for n in names)
    routes = "".join(f"ROUTE {n}.isActive TO LOG.{n}_a\nROUTE {n}.collideTime TO LOG.{n}_t\n" for n in names)
    far = ("DEF C0 Collision { children [\n" + box(0, 1.5, -40, 8, 3, 0.4, "0.3 0.3 0.8") + "\n] }\n") if extra_names else ""
    text = (HEADER + NAV + "\n" + START[0] + "\n" + FLOOR + "\nDEF INL Inline { url \"ct-live-inline-inner.wrl\" }\nIMPORT INL.C1 AS C1\n" + far + LANDMARKS
            + "\nDEF LOG Script {\n  inputOutput SFString hist \"\"\n  field SFInt32 step 0\n  outputOnly SFBool load_out\n" + fields
            + "  url \"ecmascript:\n" + funcs
            + "    function prepareEvents (t) { var e = t - 946684800;\n"
            + "      if (step == 0 && e >= 2.6) { step = 1; hist = hist + ' ' + 'load=FALSE@' + e .toFixed (6); load_out = false; }\n"
            + "      else if (step == 1 && e >= 4.3) { step = 2; hist = hist + ' ' + 'load=TRUE@' + e .toFixed (6); load_out = true; } }\n\"\n}\n"
            + routes + "ROUTE LOG.load_out TO INL.set_load\n")
    open(os.path.join(root, name + ".wrl"), "w").write(text)
    d = {"size": [SIZE, SIZE], "t0": T0, "dt": 1 / 30, "capture": [60, 78, 90, 128, 135, 160, 235], "dump": [60, 78, 79, 81, 82, 90, 128, 129, 131, 132, 135, 160, 235],
         "frames": 240, "settle": True, "console": True, "dumpInlines": True,
         "events": sorted(hold(FWD, 2, 130) + hold(BACK, 140, 60), key=lambda e: e["frame"]), "collisionProbes": PROBES}
    json.dump(d, open(os.path.join(root, "scripts", name + ".json"), "w"), indent=1)
    case(name)


live_world("ct-live-inline", [])
live_world("ct-live-inline-two", ["C0"])

open(os.path.join(root, "cases.txt"), "w").write("\n".join(" ".join(c) for c in cases) + "\n")
