#!/usr/bin/env python3
"""REA ledger entry sub:nav.collision-gravity, items C17 and C18 (docs/reports/NAV_ITEM_LISTS.md): gravity and collision with
two Layers (a LayerSet whose layers each have a ground, a Viewpoint and a NavigationInfo), and the skip of collision and
gravity while a viewpoint transition is active, observed directly. Authored from the X_ITE 16.5.0 source only
(X3DRenderObject.gravitate / collide / constrainTranslation, X3DLayerNode.collision, LayerSet.set_activeLayer__).
Worlds go to oracle/synthetic-rea-gravity-layers/*.wrl, stepped scripts to oracle/synthetic-rea-gravity-layers/scripts/*.json
(512x512, dt = 1/30, same script format as gen_rea_b24_nav.py), the case table to oracle/synthetic-rea-gravity-layers/cases.txt.

  python3 -I oracle/tools/gen_rea_gravity_layers.py
"""
import json, math, os

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "synthetic-rea-gravity-layers"))
os.makedirs(os.path.join(root, "scripts"), exist_ok=True)
cases = []
HEAD = ("#X3D V4.0 utf8\nPROFILE Immersive\nCOMPONENT Layering:1\nCOMPONENT Scripting:1\n"
        "# REA gravity/layers oracle world (generated by oracle/tools/gen_rea_gravity_layers.py).\n")


def box(cx, cy, cz, sx, sy, sz, color="0.6 0.6 0.6"):
    return (f"Transform {{ translation {cx} {cy} {cz} children Shape {{ appearance Appearance {{ material Material {{ diffuseColor {color} }} }} "
            f"geometry Box {{ size {sx} {sy} {sz} }} }} }}")


def ground(top, color):
    return box(0, top - 0.1, 0, 40, 0.2, 40, color)


def script(name, frames, events, capture, dump=(), probes=None):
    d = {"size": [512, 512], "t0": 946684800, "dt": 1 / 30, "capture": capture, "dump": list(dump), "frames": frames,
         "events": sorted(events, key=lambda e: e["frame"])}
    if probes:
        d["collisionProbes"] = probes
    json.dump(d, open(os.path.join(root, "scripts", name + ".json"), "w"), indent=1)


def case(name, world):
    cases.append((name, "oracle/synthetic-rea-gravity-layers/" + world + ".wrl"))


def hold(button, start, to, frames, f0=2):
    return [{"frame": f0, "type": "mousedown", "button": button, "x": start[0], "y": start[1]},
            {"frame": f0 + 1, "type": "mousemove", "x": to[0], "y": to[1]},
            {"frame": f0 + 1 + frames, "type": "mouseup", "button": button, "x": to[0], "y": to[1]}]


def key(frame, k):
    return {"frame": frame, "type": "key", "key": k}


def probe_directions():
    out = []
    for el in (-60, -30, 0, 30, 60):
        for az in range(0, 360, 45):
            a, e = math.radians(az), math.radians(el)
            out.append([round(math.cos(e) * math.sin(a), 6), round(math.sin(e), 6), round(-math.cos(e) * math.cos(a), 6)])
    return out + [[0, -1, 0], [0, 1, 0], [0.3, -1, 0.1], [-0.2, -1, -0.3]]


C = (256, 256)
FWD = (256, 400)  # 144 px below the center: about 4 units per second at speed 4
PROBES = probe_directions()

# The avatars: layer 0 and 1 use the default avatarSize (eye 1.6 above the ground, stepHeight 0.75), layer 2 an avatar of height 3.
NAV = 'NavigationInfo {{ type [ "WALK" ] avatarSize [ {size} ] speed 4 {extra} }}'
SIZE_STD, SIZE_TALL = "0.25 1.6 0.75", "0.25 3 0.75"


def column(x, z):
    """A Collision node beside the viewpoint (0.3 from the eye in +x for x = 0.8): isActive is TRUE while the eye is within
    collisionRadius * sqrt (2) of its face, at any height."""
    return (f"Collision {{ children [ Transform {{ translation {x} 5 {z} children Shape {{ appearance Appearance {{ material Material "
            f"{{ diffuseColor 0.8 0.3 0.3 }} }} geometry Box {{ size 1 12 1 }} }} }} ] }}")


def watcher(names):
    """A Script that records the isActive state of the Collision nodes DEF'd as `names` (a TRUE/FALSE flag each and the number
    of changes) as the WorldInfo info string, which is the compared scene text; and, when `plan` is set, switches the
    LayerSet's activeLayer at elapsed seconds since its first clock tick."""
    fields = "".join(f"  inputOnly SFBool a{i}\n" for i in range(len(names)))
    fns = "".join(f"function a{i} (v) {{ s [{i}] = v ? 1 : 0; n [{i}] += 1; show (); }}\n" for i in range(len(names)))
    routes = "".join(f"ROUTE {n}.isActive TO W.a{i}\n" for i, n in enumerate(names))
    return fields, fns, routes


def layer_world(name, active, plan=None, walls=False, trans=False):
    """Three layers: layer 0 (the root nodes), Layer 1 and Layer 2. Ground tops: 0, 2 and -1; eyes start at 1.0 (0.6 below the
    avatarHeight 1.6: a step up), 6 (falls to 3.6) and 9 (avatarHeight 3: falls to 2.0). A Collision column stands beside each
    eye. `plan` is a list of (seconds, layer) for the Script that switches activeLayer. `walls`: a wall in layer 0 at z = 7
    and one in layer 1 at z = 2 (for the walk-forward cases)."""
    nav0 = NAV.format(size=SIZE_STD, extra="")
    nav1 = NAV.format(size=SIZE_STD, extra="")
    nav2 = NAV.format(size=SIZE_TALL, extra="")
    wall = lambda z: ("Collision { children [ " + box(0, 5, z, 12, 10, 0.4, "0.8 0.3 0.3") + " ] }")
    names = ["COL0", "COL1", "COL2"]
    fields, fns, routes = watcher(names)
    sw = ""

    if plan:
        sw = ("DEF CLK TimeSensor { loop TRUE cycleInterval 1000 }\nROUTE CLK.time TO W.tick\n")

    t = HEAD + nav0 + '\nViewpoint { position 0 1 12 description "layer 0" }\n' + ground(0, "0.4 0.4 0.4") + "\n"
    t += "DEF COL0 " + column(0.8, 12) + "\n"

    if walls:
        t += wall(7) + "\n"

    t += f"DEF LS LayerSet {{ activeLayer {active} order [ 0 1 2 ] layers [\n"
    t += "  DEF L1 Layer { children [\n    " + nav1 + '\n    Viewpoint { position 0 6 12 description "layer 1" }\n    ' + ground(2, "0.3 0.5 0.3") + "\n    "
    t += "DEF COL1 " + column(0.8, 12) + "\n"

    if walls:
        t += "    " + wall(2) + "\n"

    t += "  ] }\n"
    t += "  DEF L2 Layer { children [\n    " + nav2 + '\n    Viewpoint { position 0 9 12 description "layer 2" }\n    ' + ground(-1, "0.3 0.3 0.5") + "\n    "
    t += "DEF COL2 " + column(0.8, 12) + "\n  ] }\n] }\n"
    t += 'DEF INFO WorldInfo { title "gravity layers" info [ "s=000 n=000" ] }\n'

    plan_js = json.dumps(plan or [])
    t += ("DEF W Script {\n  directOutput TRUE\n  inputOnly SFTime tick\n" + fields
          + "  initializeOnly SFNode ls USE LS\n  initializeOnly SFNode info USE INFO\n  url \"ecmascript:\n"
          + "var s = [ 0, 0, 0 ], n = [ 0, 0, 0 ], first = -1, next = 0, plan = " + plan_js + ";\n"
          + "function show () { info .info = new MFString ('s=' + s [0] + s [1] + s [2] + ' n=' + n [0] + n [1] + n [2]); }\n"
          + fns
          + "function tick (value)\n{\n   if (first < 0) first = value;\n   var e = value - first;\n"
          + "   while (next < plan .length && e >= plan [next][0] - 1e-6) { ls .activeLayer = plan [next][1]; ++ next; }\n}\n\"\n}\n")
    t += routes + sw
    open(os.path.join(root, name + ".wrl"), "w").write(t)


# --- C17: static active layer 0, 1, 2 ------------------------------------------------------------------------------------
# The active layer's eye steps up (layer 0), or falls (layer 1: 6 to 3.6, layer 2: 9 to 2.0); the collision probes after the last
# frame use the active layer's collision shapes; the scene text records the isActive state of the three Collision columns
# (collide runs for every layer; gravitate and the viewer's constrained moves only for the active one).
for a in (0, 1, 2):
    layer_world(f"layers-gravity-active{a}", a)
    script(f"layers-gravity-active{a}", 80, [], [1, 2, 3, 5, 8, 12, 20, 30, 50, 80], dump=[1, 80], probes=PROBES)
    case(f"layers-gravity-active{a}", f"layers-gravity-active{a}")

# --- C17: switching the active layer at run time -------------------------------------------------------------------------
# Layer 1 is active and falls from 6 to 3.6; then layer 2 (never active so far: if gravity ran for it, it would be at 2.0 already)
# falls from 9, then layer 0 steps up from 1, then layer 1 again (already at rest).
sw_plan = [(1.5, 2), (3.5, 0), (5.0, 1)]
layer_world("layers-gravity-switch", 1, sw_plan)
cap = [20, 30, 44, 45, 46, 47, 48, 50, 55, 60, 70, 100, 104, 105, 106, 107, 110, 140, 149, 150, 151, 152, 155, 170, 190]
script("layers-gravity-switch", 190, [], cap, dump=[30, 105, 190], probes=PROBES)
case("layers-gravity-switch", "layers-gravity-switch")

# Switch in the middle of layer 1's fall (fall speed != 0) to layer 2, back to layer 1 after layer 2 has settled.
mid_plan = [(0.2, 2), (2.0, 1)]
layer_world("layers-gravity-midfall", 1, mid_plan)
script("layers-gravity-midfall", 120, [], [3, 5, 6, 7, 8, 10, 20, 40, 59, 60, 61, 62, 63, 64, 66, 70, 80, 100, 120], dump=[120], probes=PROBES)
case("layers-gravity-midfall", "layers-gravity-midfall")

# --- C17: collision walls per layer: only the active layer's walls stop the walk -----------------------------------------
# A wall at z = 7 in layer 0 and a wall at z = 2 in layer 1; the eye starts at z = 12. Walking forward from layer 1 passes z = 7 and
# stops at the layer 1 wall; walking from layer 0 stops at the layer 0 wall.
for a in (0, 1):
    layer_world(f"layers-walls-active{a}", a, walls=True)
    script(f"layers-walls-active{a}", 190, hold(0, C, FWD, 130, f0=40), [30, 60, 80, 100, 120, 140, 170, 190], dump=[190], probes=PROBES)
    case(f"layers-walls-active{a}", f"layers-walls-active{a}")

# --- C18: collision and gravity are skipped while a transition is active -----------------------------------------------------
# NavigationInfo transitionTime 2 (LINEAR). Viewpoint A (0 1.6 12) is on the ground, viewpoint B (0 6 0) is in the air behind a Collision wall at z = 6.
# PageDown at frame 10 starts the transition; during it gravity does not pull (no fall), the eye passes through the wall and the
# wall's isActive stays FALSE (the scene text counts its changes). After the transition the eye falls and X_ITE resumes collision.
TRANS_NAV = 'NavigationInfo { type [ "WALK" ] avatarSize [ 0.25 1.6 0.75 ] speed 4 transitionType [ "LINEAR" ] transitionTime 2 }'


def trans_world(name, layered):
    t = HEAD
    wallnode = "DEF COLW Collision { children [ " + box(0, 4, 6, 8, 8, 0.4, "0.8 0.3 0.3") + " ] }"
    body = (TRANS_NAV + '\nViewpoint { position 0 1.6 12 description "A ground" }\nViewpoint { position 0 6 0 description "B air" }\n'
            + ground(0, "0.4 0.4 0.4") + "\n" + wallnode + "\n")

    if not layered:
        t += body
    else:
        # The second layer has its own (non-transitioning) viewpoint and wall: its collide keeps running during layer 1's transition.
        t += ('NavigationInfo { type [ "WALK" ] avatarSize [ 0.25 1.6 0.75 ] speed 4 }\nViewpoint { position 0 1.6 12 description "layer 0" }\n'
              + ground(0, "0.4 0.4 0.4") + "\n")
        t += "DEF LS LayerSet { activeLayer 1 order [ 0 1 ] layers [\n  DEF L1 Layer { children [\n    " + body.replace("\n", "\n    ") + "\n  ] }\n] }\n"

    t += 'DEF INFO WorldInfo { title "transition" info [ "s=0 n=0" ] }\n'
    t += ("DEF W Script {\n  inputOnly SFBool a0\n  initializeOnly SFNode info USE INFO\n  url \"ecmascript:\n"
          "var n = 0;\nfunction a0 (v) { n += 1; info .info = new MFString ('s=' + (v ? 1 : 0) + ' n=' + n); }\n\"\n}\nROUTE COLW.isActive TO W.a0\n")
    open(os.path.join(root, name + ".wrl"), "w").write(t)


trans_world("trans-gravity-skip", False)
script("trans-gravity-skip", 150, [key(10, "PageDown")], [9, 10, 11, 12, 20, 30, 40, 50, 60, 68, 69, 70, 71, 72, 74, 80, 100, 150], dump=[9, 30, 60, 150], probes=PROBES)
case("trans-gravity-skip", "trans-gravity-skip")
# Ending in the first frame of the transition (the eye has not moved yet) with the collision probes: the shapes of the last
# collision pass are still the right ones.
script("trans-skip-probe-start", 10, [key(10, "PageDown")], [9, 10], dump=[10], probes=PROBES)
case("trans-skip-probe-start", "trans-gravity-skip")
# The same, ending in the middle of the transition: X_ITE does not render the collision pass during the transition, so the probes
# read the shapes (and their old view-space matrices) of the last frame before it.
script("trans-skip-probe", 40, [key(10, "PageDown")], [9, 10, 20, 40], dump=[40], probes=PROBES)
case("trans-skip-probe", "trans-gravity-skip")
# Transition in the active Layer 1 of a LayerSet (layer 0 is not active); the probes after the transition end are fresh again.
trans_world("trans-layer-skip", True)
script("trans-layer-skip", 150, [key(10, "PageDown")], [9, 10, 11, 12, 20, 30, 40, 50, 60, 68, 69, 70, 71, 72, 74, 80, 100, 150], dump=[9, 30, 60, 150], probes=PROBES)
case("trans-layer-skip", "trans-layer-skip")
script("trans-layer-probe", 40, [key(10, "PageDown")], [9, 10, 20, 40], dump=[40], probes=PROBES)
case("trans-layer-probe", "trans-layer-skip")

with open(os.path.join(root, "cases.txt"), "w") as f:
    for name, w in cases:
        f.write(f"{name} {w} oracle/synthetic-rea-gravity-layers/scripts/{name}.json\n")
print(len(cases), "cases")
