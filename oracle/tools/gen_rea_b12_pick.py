F = 1 / math.tan(0.7854 / 2)


def rot(axis, angle):
    x, y, z = axis
    n = math.sqrt(x * x + y * y + z * z)
    x, y, z = x / n, y / n, z / n
    c, s, t = math.cos(angle), math.sin(angle), 1 - math.cos(angle)
    return [[t * x * x + c, t * x * y - s * z, t * x * z + s * y],
            [t * x * y + s * z, t * y * y + c, t * y * z - s * x],
            [t * x * z - s * y, t * y * z + s * x, t * z * z + c]]


def xf(p, tr=(0, 0, 0), r=None, sc=(1, 1, 1)):
    """Transform { translation tr rotation r scale sc } applied to p (no center / scaleOrientation)."""
    q = [p[0] * sc[0], p[1] * sc[1], p[2] * sc[2]]
    if r:
        m = rot(r[:3], r[3])
        q = [sum(m[i][k] * q[k] for k in range(3)) for i in range(3)]
    return [q[0] + tr[0], q[1] + tr[1], q[2] + tr[2]]


def screen(p):
    """World point -> pointer coordinates (x from the left, y from the bottom), the camera at 0 0 10 looking down -Z."""
    z = 10 - p[2]
    return [(p[0] * F / z + 1) / 2 * SIZE, (p[1] * F / z + 1) / 2 * SIZE]


def point_probes(pts, r=1.25, step=0.25):
    out = []
    n = int(round(r / step))
    for p in pts:
        cx, cy = screen(p)
        out += [[round(cx + i * step, 4), round(cy + j * step, 4)] for i in range(-n, n + 1) for j in range(-n, n + 1)]
    return out


def segment_probes(a, b, along=9, r=1.5, step=0.25):
    (ax, ay), (bx, by) = screen(a), screen(b)
    dx, dy = bx - ax, by - ay
    length = math.hypot(dx, dy) or 1
    nx, ny = -dy / length, dx / length
    n = int(round(r / step))
    out = []
    for i in range(1, along + 1):
        t = i / (along + 1)
        px, py = ax + dx * t, ay + dy * t
        out += [[round(px + nx * k * step, 4), round(py + ny * k * step, 4)] for k in range(-n, n + 1)]
    return out


def write(name, text):
    open(os.path.join(root, name + ".wrl"), "w").write(text)


def script(name, frames=2, events=(), probes=None, capture=None):
    d = {"size": [SIZE, SIZE], "t0": 946684800, "dt": 1 / 30, "settle": False, "frames": frames, "capture": capture or [],
         "dump": sorted(set((capture or []) + [frames - 1])), "events": sorted(events, key=lambda e: e["frame"])}
    if probes is not None:
        d["pickProbes"] = probes
    json.dump(d, open(os.path.join(root, name + ".json"), "w"), indent=1)


def fmt(pts):
    return ", ".join(" ".join(f"{c:g}" for c in p) for p in pts)


