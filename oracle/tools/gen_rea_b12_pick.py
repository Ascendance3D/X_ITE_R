"""REA batch 12 picking lane: pointing-buffer hits on points and lines (geometry types 0 and 1), overlapping targets and the
nearest hit, as probe grids (script key pickProbes, compared bit for bit) and stepped TouchSensor event worlds
(oracle/synthetic-rea-b12-pick). 512x512, Viewpoint at 0 0 10 with the default fieldOfView, pointer y from the bottom.

X_ITE draws points with gl.POINTS (gl_PointSize 2, or max (getPointSize, 2) with PointProperties) and lines with gl.LINES
(width 1) or, with LineProperties, as transformed triangles into the 1x1 RGBA32F pointing buffer (Pointing2.vs / .fs).
The probes sit on a sub-pixel grid around every projected point and across every projected line segment.

  pk-points        PointSet (plain, colored, transformed, with normals), points in front of / inside / behind a Box, ClipPlane
  pk-points-style  PointSet + PointProperties: gl_PointSize from attenuation, the round point mask, gl_PointCoord texCoord
  pk-lines         IndexedLineSet, LineSet (vertexCount), lines in front of / through / behind a Box, a line on a face, an
                   aliased wide line (width 5), a transformed thick line (width 14), axis-aligned lines, normals, ClipPlane
  pk-overlap       coincident and stacked targets: two Boxes sharing a face, points on a face, nested Transforms with scale
                   and rotation, the same geometry USEd twice at different depths, a ring with a hole, a ClipPlane
  pk-events   TouchSensor events over points, lines and stacked shapes: moves across, press and release without movement,
              repeated press at one position, a drag off the shape

  python3 -I -B oracle/tools/gen_rea_b12_pick.py
"""
