#!/usr/bin/env python3
"""Synthetic GaussianSplats pointing worlds (issue #69, pass 3) and their probe scripts.

  python3 -I -B oracle/tools/gen_b69_gs_pick.py

writes oracle/synthetic-b69-gs-pick/NAME.x3dv and scripts/NAME.json. Every world holds the dummy ParticleSystem PS that
`x3d-oracle particles` needs (as oracle/synthetic-rea-b23-depthmode-pick does) and is probed with `browser .touch (x, y)` on
a grid of pixel centers of the 512 x 512 canvas. All splat data are synthetic (seeded pseudo-random).
"""
import json, os, random

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
out = os.path.join(root, "oracle", "synthetic-b69-gs-pick")
os.makedirs(os.path.join(out, "scripts"), exist_ok=True)



def gs(seed, n, box, extra="", scale=(0.12, 0.35)):
    r = random.Random(seed)
    pos, ori, sc, op, sh = [], [], [], [], []
    for _ in range(n):
        pos.append(" ".join("%.4f" % r.uniform(-b, b) for b in box))
        q = [r.uniform(-1, 1) for _ in range(4)]
        l = sum(v * v for v in q) ** 0.5
        ori.append(" ".join("%.4f" % (v / l) for v in q))
        sc.append(" ".join("%.4f" % r.uniform(*scale) for _ in range(3)))
        op.append("%.3f" % r.uniform(0.5, 0.95))
        sh.append(" ".join("%.4f" % r.uniform(-0.8, 1.2) for _ in range(3)))
    return ("GaussianSplats {\n  %s\n  positions [ %s ]\n  orientations [ %s ]\n  scales [ %s ]\n  opacities [ %s ]\n"
            "  sphericalHarmonicsDegree0Coef0 [ %s ]\n}" % (extra, ", ".join(pos), ", ".join(ori), ", ".join(sc), ", ".join(op), ", ".join(sh)))


def box(z, size, extra=""):
    return ("Transform { translation 0 0 %s children Shape { %s appearance Appearance { material Material { diffuseColor 0.8 0.2 0.2 } } "
            "geometry Box { size %s %s %s } } }" % (z, extra, size, size, size))


TRUE = "pointerEvents TRUE"
worlds = {
    # Two TRUE nodes: the nearer splat center wins, whatever the node order.
    "gs-pick-basic": [
        "Viewpoint { position 0 0 10 }",
        "Transform { translation 0.3 0 -2 children %s }" % gs(1, 70, (2.2, 2.2, 1.0), TRUE),
        "Transform { translation -0.3 0.2 0 children %s }" % gs(2, 70, (2.2, 2.2, 1.0), TRUE),
    ],
    # pointerEvents is FALSE by default for GaussianSplats: the front node is not a pointing object.
    "gs-pick-default": [
        "Viewpoint { position 0 0 10 }",
        "Transform { translation 0 0 -2 children %s }" % gs(3, 70, (2.2, 2.2, 1.0), TRUE),
        "Transform { translation 0.2 0 1 children %s }" % gs(4, 70, (2.2, 2.2, 1.0)),
    ],
    "gs-pick-xform": [
        "Viewpoint { position 0 0 10 }",
        "Transform { translation 0.5 -0.3 0 rotation 0 1 0 0.7 scale 1.3 0.8 1 children %s }" % gs(5, 90, (2.0, 2.0, 1.5), TRUE),
    ],
    "gs-pick-clip": [
        "Viewpoint { position 0 0 10 }",
        "Group { children [ ClipPlane { plane 1 0.4 0 0.2 } %s ] }" % gs(6, 90, (2.4, 2.4, 1.0), TRUE),
    ],
    # A Shape (pointerEvents TRUE by default) behind and in front of the splats: ids follow the traversal order.
    "gs-pick-mixed": [
        "Viewpoint { position 0 0 10 }",
        box(-3, 3.5),
        "Transform { translation 0 0 0 children %s }" % gs(7, 60, (2.0, 2.0, 0.6), TRUE),
        "Transform { translation 1.2 0.9 2.5 children %s }" % box(0, 1.0),
        box(-0.2, 1.2, "pointerEvents FALSE"),
    ],
    "gs-pick-ortho": [
        "OrthoViewpoint { position 0 0 10 }",
        "Transform { translation 0 0 -1 scale 0.4 0.4 0.4 children %s }" % gs(10, 80, (2.4, 2.4, 1.0), TRUE),
    ],
}

pts = [[x + 0.5, y + 0.5] for y in range(12, 512, 24) for x in range(12, 512, 24)]
script = {"dt": 1 / 30, "t0": 946684800, "frames": 3, "warmup": 8, "node": "PS", "dump": [3], "seed": 69000001,
          "pickProbes": {"frames": [3], "points": pts}}

for name, kids in worlds.items():
    with open(os.path.join(out, name + ".x3dv"), "w") as f:
        f.write("#X3D V4.1 utf8\nPROFILE Full\nCOMPONENT X_ITE:1\nCOMPONENT GaussianSplats:1\n")
        f.write("# Synthetic pointing world for GaussianSplats (generated by oracle/tools/gen_b69_gs_pick.py).\n")
        f.write("DEF PS ParticleSystem { enabled FALSE maxParticles 1 geometryType \"POINT\" }\n")
        f.write("\n".join(kids) + "\n")
    with open(os.path.join(out, "scripts", name + ".json"), "w") as f:
        json.dump(script, f)
print(len(worlds), "worlds,", len(pts), "probes each")
