def logger(names):
    fields, routes, funcs = "", "", ""
    for s in names:
        for i, (o, t) in enumerate(outs):
            fn = f"{s}{i}"
            fields += f"  inputOnly {t} {fn}\n"
            routes += f"ROUTE {s}.{o} TO LOG.{fn}\n"
            val = "(v - 946684800) .toFixed (4)" if t == "SFTime" else "v"
            funcs += f"    function {fn} (v, t) {{ hist = hist + ' ' + frame + ':{s}.{o}=' + {val}; }}\n"
    return ("DEF LOG Script {\n  inputOutput SFString hist \"\"\n  inputOutput SFInt32 frame 0\n" + fields + "  url \"ecmascript:\n" + funcs
            + "    function prepareEvents () { frame = frame + 1; }\n\"\n}\n" + routes)


class Mouse:
    def __init__(self, f=3):
        self.f, self.ev = f, []

    def mv(self, p, dx=0.0, dy=0.0):
        self.ev.append({"frame": self.f, "type": "mousemove", "x": round(p[0] + dx, 3), "y": round(p[1] + dy, 3)}); self.f += 2

    def press(self, p, button=0):
        self.ev.append({"frame": self.f, "type": "mousedown", "button": button, "x": round(p[0], 3), "y": round(p[1], 3)}); self.f += 2

    def release(self, p, button=0):
        self.ev.append({"frame": self.f, "type": "mouseup", "button": button, "x": round(p[0], 3), "y": round(p[1], 3)}); self.f += 2

    def click(self, p):
        self.mv(p); self.press(p); self.release(p)

    def key(self, k):
        self.ev.append({"frame": self.f, "type": "key", "key": k}); self.f += 3


