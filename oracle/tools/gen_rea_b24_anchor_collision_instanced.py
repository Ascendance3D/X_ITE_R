SIZE = 512
F = 1 / math.tan(0.7854 / 2)


def screen(p):
    z = 10 - p[2]
    return [(p[0] * F / z + 1) / 2 * SIZE, (p[1] * F / z + 1) / 2 * SIZE]


def grid(step=10, off=3.25):
    n = int((SIZE - off) // step)
    return [[off + i * step, off + j * step] for j in range(n + 1) for i in range(n + 1)]


def write(name, text):
    open(os.path.join(root, name + ".wrl"), "w").write(text)


def script(name, frames=2, events=(), probes=None, capture=None):
    d = {"size": [SIZE, SIZE], "t0": 946684800, "dt": 1 / 30, "settle": False, "frames": frames, "capture": capture or [],
         "dump": sorted(set((capture or []) + [frames - 1])), "events": sorted(events, key=lambda e: e["frame"])}
    if probes is not None:
        d["pickProbes"] = probes
    json.dump(d, open(os.path.join(root, name + ".json"), "w"), indent=1)


