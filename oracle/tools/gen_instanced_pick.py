#!/usr/bin/env python3
"""InstancedShape and the picking engine (Components/Picking, TransformSensor) against pinned X_ITE 16.5.0.

X_ITE's InstancedShape picks like a Shape: X3DShapeNode.picking collects the base geometry once under the shape's own
model matrix, never under the instance matrices, and a pickTarget of the InstancedShape itself is not a target
(X3DPickSensorNode.set_pickTarget__ takes Inline, Shape and X3DGroupingNode types only). TransformSensor.targetObject takes any
X3DShapeNode, which includes an InstancedShape.

Row r of ip-sweep: a mover (a Transform that a PositionInterpolator sweeps along x) carries one LinePickSensor with GEOMETRY and
one with BOUNDS, a PrimitivePickSensor, a VolumePickSensor and a PointPickSensor, all with the row's target. Row 6 has two
TransformSensors on a moving InstancedShape (the shape itself and its Transform). The sensors' outputs are routed to a Script
that logs frame:event strings, which the scene text dump carries (the frame counter follows prepareEvents).

  python3 -I -B oracle/tools/gen_instanced_pick.py
"""
import json, os

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "synthetic-instanced-pick"))
os.makedirs(root, exist_ok=True)
HEAD = ("#X3D V4.0 utf8\nPROFILE Full\nCOMPONENT X_ITE:1\nCOMPONENT Picking:3\nCOMPONENT Scripting:1\n"
        "# Instanced picking oracle world (generated by oracle/tools/gen_instanced_pick.py).\n")
EMISSIVE = lambda c: f"Appearance {{ material Material {{ emissiveColor {c} }} }}"
FRAMES = 140
T0 = 946684800

# (row y, target text, pickTarget list or None for "the group")
ROWS = [
    (0, "Transform { children InstancedShape { translations [ 0 0 0, 4 0 0, 8 0 0 ] geometry Box { size 2 2 2 } } }", "G"),
    (6, "Transform { translation 1 0 0 rotation 0 0 1 0.5 children InstancedShape { translations [ 3 0 0, 6 0 0 ] "
        "geometry Sphere { radius 1 } } }", "G"),
    (-6, "Transform { translation 2 0 0 scale 1.5 1 1 children InstancedShape { translations [ 0 0 0, 5 0 0 ] "
         "scales [ 1 1 1, 3 3 3 ] rotations [ 0 0 1 0, 0 0 1 0.8 ] geometry Cone { bottomRadius 1 height 2 } } }", "G"),
    (12, "Transform { children InstancedShape { geometry Box { size 2 2 2 } } }", "G"),
    (-12, "DEF I4 InstancedShape { translations [ 0 0 0, 4 0 0 ] geometry Box { size 2 2 2 } }", "I4"),
]
KINDS = [("LG", "LinePickSensor", 'intersectionType "GEOMETRY" sortOrder "ALL_SORTED"', "LINE", True),
         ("LB", "LinePickSensor", 'intersectionType "BOUNDS" sortOrder "ALL"', "LINE", False),
         ("PR", "PrimitivePickSensor", "", "PRIM", False),
         ("VO", "VolumePickSensor", "", "VOL", False),
         ("PO", "PointPickSensor", "", "POINT", True)]
GEOM = {"LINE": "IndexedLineSet { coord Coordinate { point [ 0 -1.6 0, 0 1.6 0 ] } coordIndex [ 0 1 -1 ] }",
        "PRIM": "Sphere { radius 0.3 }", "VOL": "Box { size 0.4 0.4 0.4 }",
        "POINT": "PointSet { coord Coordinate { point [ 0 -0.5 0, 0 0.5 0, 0 0 0 ] } }"}

fields, funcs, routes, body = [], [], [], ""


def log(tag, ty, out, expr):
    n = f"{tag}_{out}"
    fields.append(f"  inputOnly {ty} {n}")
    funcs.append(f"function {n} (v) {{ hist = hist + ' ' + frame + ':{tag}.{out}=' + ({expr}); }}")
    routes.append(f"ROUTE {tag.split('.')[0]}.{out} TO R.{n}")


body += HEAD + "Viewpoint { position 0 0 40 }\nNavigationInfo { type \"NONE\" }\n"
body += "DEF CLOCK TimeSensor { cycleInterval 4 loop TRUE }\n"
for r, (y, target, pt) in enumerate(ROWS):
    if pt == "G":
        body += f"DEF G{r} PickableGroup {{ children [ Transform {{ translation 0 {y} 0 children [ {target} ] }} ] }}\n"
        pick_target = f"USE G{r}"
    else:
        body += f"PickableGroup {{ children [ Transform {{ translation 0 {y} 0 children [ {target} ] }} ] }}\n"
        pick_target = f"USE {pt}"
    body += f"DEF M{r} Transform {{ translation -8 {y} 0 children [\n"
    for k, ty, extra, g, with_point in KINDS:
        s = f"S{r}{k}"
        body += f"  Shape {{ appearance {EMISSIVE('1 1 1')} geometry DEF {s}G {GEOM[g]} }}\n"
        body += f"  DEF {s} {ty} {{ {extra} pickingGeometry USE {s}G pickTarget [ {pick_target} ] }}\n"
        log(s, "SFBool", "isActive", "v")
        log(s, "MFNode", "pickedGeometry", "v .length")
        if with_point:
            log(s, "MFVec3f", "pickedPoint", "v .length ? v [0] .x .toFixed (2) + ',' + v [0] .y .toFixed (2) : 'none'")
    body += "] }\n"
    body += f"DEF P{r} PositionInterpolator {{ key [ 0 1 ] keyValue [ -8 {y} 0, 14 {y} 0 ] }}\n"
    body += f"ROUTE CLOCK.fraction_changed TO P{r}.set_fraction\nROUTE P{r}.value_changed TO M{r}.set_translation\n"

# Row 6: TransformSensors on a moving InstancedShape.
body += "DEF M6 Transform { translation -8 18 0 children DEF I6 InstancedShape { translations [ 0 0 0, 5 0 0 ] rotations [ 0 0 1 0.3 ] geometry Box { size 1 1 1 } } }\n"
body += "DEF P6 PositionInterpolator { key [ 0 1 ] keyValue [ -8 18 0, 14 18 0 ] }\n"
body += "ROUTE CLOCK.fraction_changed TO P6.set_fraction\nROUTE P6.value_changed TO M6.set_translation\n"
body += "DEF TSI TransformSensor { size 6 6 6 center 0 18 0 targetObject USE I6 }\n"
body += "DEF TSM TransformSensor { size 6 6 6 center 0 18 0 targetObject USE M6 }\n"
for tag in ("TSI", "TSM"):
    log(tag, "SFBool", "isActive", "v")
    log(tag, "SFVec3f", "position_changed", "v .x .toFixed (2) + ',' + v .y .toFixed (2) + ',' + v .z .toFixed (2)")
    log(tag, "SFRotation", "orientation_changed", "v .angle .toFixed (2)")

body += ("DEF R Script {\n  initializeOnly SFInt32 frame 0\n  inputOutput SFString hist \"\"\n" + "\n".join(fields) + "\n"
         + '  url "ecmascript:\n' + "\n".join(funcs) + "\nfunction prepareEvents () { frame = frame + 1; }\n\"\n}\n" + "\n".join(routes) + "\n")
open(os.path.join(root, "ip-sweep.wrl"), "w").write(body)
json.dump({"size": [512, 512], "t0": T0, "dt": 1 / 30, "settle": False, "frames": FRAMES, "capture": [], "dump": [70, FRAMES - 1],
           "events": []}, open(os.path.join(root, "ip-sweep.json"), "w"), indent=1)
print("ip-sweep:", len(KINDS) * len(ROWS), "pick sensors, 2 transform sensors")
