#!/usr/bin/env python3
"""Generated summary of the coverage ledger: python3 -I -B ledger/tools/ledger_summary.py [--check]

Reads ledger/ledger.json and writes ledger/SUMMARY.md: the status totals, the classification totals of the DIFFERENT
entries, and each PARTIAL entry with its `missing` field (the remaining requirements). The file holds the sha256 of the
ledger it was made from and no date or commit, so the same ledger always gives the same bytes.
--check writes nothing and exits 1 when ledger/SUMMARY.md is not what this tool writes (CI runs it; after a ledger step,
run the tool without --check and commit SUMMARY.md with the step). This tool reads the ledger and never changes it."""
import collections, hashlib, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
LEDGER = os.path.join(HERE, "..", "ledger.json")
OUT = os.path.join(HERE, "..", "SUMMARY.md")
ORDER = ["COMPLETE", "PARTIAL", "DIFFERENT", "MISSING", "NOT_TESTED"]


def cell(s):
    return " ".join(str(s).split()).replace("|", "\\|")


def render():
    raw = open(LEDGER, "rb").read()
    items = json.loads(raw)["items"]
    st = collections.Counter(i["status"] for i in items)
    cl = collections.Counter(i["classification"]["class"] for i in items if "classification" in i)
    out = [
        "# Coverage ledger summary",
        "",
        "Generated by `python3 -I -B ledger/tools/ledger_summary.py` from `ledger/ledger.json`. Do not edit by hand.",
        "`ledger/tools/verify_ledger.py` checks the ledger itself; CI runs both (`ledger_summary.py --check`).",
        "",
        f"Ledger sha256: `{hashlib.sha256(raw).hexdigest()}`",
        "",
        "## Status totals",
        "",
        "| status | entries |",
        "| --- | --- |",
    ]
    out += [f"| {s} | {st.get(s, 0)} |" for s in ORDER]
    out += [f"| total | {len(items)} |", ""]
    out += [
        "## Classification of the DIFFERENT entries",
        "",
        "The `classification` field is independent of `status` and does not change the totals above.",
        "",
        "| class | entries |",
        "| --- | --- |",
    ]
    out += [f"| {c} | {n} |" for c, n in sorted(cl.items())]
    out += [f"| total | {sum(cl.values())} |", ""]
    out += [
        "| entry | class | impact |",
        "| --- | --- | --- |",
    ]
    out += [
        f"| `{i['id']}` | {i['classification']['class']} | {cell(i['classification'].get('impact', ''))} |"
        for i in items
        if "classification" in i
    ]
    out += [
        "",
        "## PARTIAL entries and their remaining requirements",
        "",
        "Each row is the entry's `missing` field. The entry's `notes`, `tests` and `oracle` fields hold the evidence.",
        "",
        "| entry | remaining requirements (`missing`) |",
        "| --- | --- |",
    ]
    out += [f"| `{i['id']}` | {cell(i.get('missing') or '(empty)')} |" for i in items if i["status"] == "PARTIAL"]
    for s in ("MISSING", "NOT_TESTED"):
        rows = [i for i in items if i["status"] == s]
        if rows:
            out += ["", f"## {s} entries", ""] + [f"- `{i['id']}`: {cell(i.get('missing') or '')}" for i in rows]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    if sys.argv[1:] not in ([], ["--check"]):
        raise SystemExit("usage: ledger_summary.py [--check]")
    text = render()
    if sys.argv[1:] == ["--check"]:
        try:
            cur = open(OUT, encoding="utf-8").read()
        except FileNotFoundError:
            cur = None
        if cur != text:
            print("ledger/SUMMARY.md is not current: run python3 -I -B ledger/tools/ledger_summary.py")
            sys.exit(1)
        print("ledger/SUMMARY.md is current")
        sys.exit(0)
    tmp = OUT + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, OUT)
    print(f"wrote {os.path.relpath(OUT)}")
