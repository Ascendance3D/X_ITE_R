#!/usr/bin/env python3
"""Issue #90 second step (node:Appearance): python3 -I ledger_i90b.py check|apply

alphaMode and alphaCutoff are applied by the renderer since PR #184 (crates/x3d-render/tests/alpha_mode.rs, 4 cases, and vis-items-alpha in render_rea_b09_visual.rs, no longer a KNOWN_GAPS world, passing at MSAA 0 and 4 against three identical pinned X_ITE 16.5.0 recordings). The entry becomes COMPLETE. No DIFFERENT entry is in the change set."""
import json, os, sys, collections, hashlib
HERE = os.path.dirname(os.path.abspath(__file__))
AUTH = os.path.join(HERE, "..", "ledger", "ledger.json")
SNAP = os.path.join(HERE, "..", "ledger", "before-i90b", "ledger.json")
SNAP_SHA256 = "ba91f8aec4adb02dcc426b243750c7aa70d4d7e0f70fe643fda5dbeb05557ef1"

T = ["crates/x3d-render/tests/alpha_mode.rs (4 cases: AlphaMode names, transparency resolution, cutoff only for MASK, shapes carry the mode and cutoff)"]
FIELDS = {"tests": lambda old: old + T, "missing": ""}
NOTE = "Issue #90 2026-11-01: alphaMode and alphaCutoff are applied (PR #184); vis-items-alpha is removed from KNOWN_GAPS and matches pinned X_ITE at MSAA 0 and 4 on the RTX 3060 Ti (render_rea_b09_visual: pass). alpha_mode.rs: 4 cases pass."
C = {"node:Appearance": ("COMPLETE", FIELDS, NOTE)}

def load(p): return json.load(open(p))
def build():
    d = load(SNAP)
    for i in d["items"]:
        if i["id"] in C:
            s, fields, note = C[i["id"]]
            if s: i["status"] = s
            for f, v in fields.items(): i[f] = v(i[f]) if callable(v) else v
            if note: i["notes"] = (i["notes"] + " | " if i["notes"] else "") + note
    return d
def check(d):
    bad, snap = [], {i["id"]: i for i in load(SNAP)["items"]}
    cur = {i["id"]: i for i in d["items"]}
    if set(cur) != set(snap) or len(d["items"]) != 346: bad.append("ID set or total changed")
    if [i["id"] for i in d["items"]] != [i["id"] for i in load(SNAP)["items"]]: bad.append("ID order changed")
    want = {i["id"]: i for i in build()["items"]}
    for k, b in snap.items():
        a = cur[k]
        if k not in C and a != b: bad.append(f"unrelated entry changed: {k}")
        if b["status"] == "DIFFERENT" and a != b: bad.append(f"DIFFERENT changed: {k}")
        if k in C and (a["status"] != (C[k][0] or b["status"]) or not a["notes"].startswith(b["notes"])): bad.append(f"{k}: status or notes")
        if k in C and a != want[k]: bad.append(f"{k}: differs from what apply writes")
    c = collections.Counter(i["status"] for i in d["items"]); print(dict(sorted(c.items())))
    print("\n".join(bad) or "OK"); return not bad
def sha256(p):
    with open(p, "rb") as f: return hashlib.sha256(f.read()).hexdigest()
def snap_ok():
    got = sha256(SNAP)
    if got != SNAP_SHA256: print(f"snapshot sha256 {got} is not the expected {SNAP_SHA256}: refused"); return False
    return True
if __name__ == "__main__":
    if sys.argv[1:] not in (["check"], ["apply"]): raise SystemExit("usage: ledger_i90b.py check|apply")
    if not snap_ok(): sys.exit(1)
    if sys.argv[1:] == ["apply"]:
        d = build()
        try: same = sha256(AUTH) == SNAP_SHA256 or load(AUTH) == d
        except ValueError: same = False
        if not same:
            print("ledger.json is neither the snapshot nor the result of this change set: refused"); sys.exit(1)
        tmp = AUTH + ".tmp"
        with open(tmp, "w") as f:
            json.dump(d, f, indent=1); f.flush(); os.fsync(f.fileno())
        os.replace(tmp, AUTH); sys.exit(0 if check(load(AUTH)) else 1)
    sys.exit(0 if check(load(AUTH)) else 1)
