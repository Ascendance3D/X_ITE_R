#!/usr/bin/env bash
# Build the X_ITE_R page module: crates/x3d-web for wasm32-unknown-unknown, then wasm-bindgen into
# crates/x3d-web/web/pkg (gitignored). The page imports it through crates/x3d-web/web/x_ite_r.mjs.
#
#   tools/build-web.sh [--debug]
#
# Needs the wasm32-unknown-unknown target (rustup target add wasm32-unknown-unknown) and wasm-bindgen-cli
# of the exact wasm-bindgen version in Cargo.lock (cargo install wasm-bindgen-cli --version <v> --locked).
# WASM_BINDGEN overrides the wasm-bindgen executable.
set -euo pipefail

cd "$(dirname "$0")/.."

profile=release
flags=(--release)

if [[ "${1:-}" == "--debug" ]]; then
  profile=debug
  flags=()
fi

want=$(awk '/^name = "wasm-bindgen"$/ { getline; gsub(/version = |"/, ""); print; exit }' Cargo.lock)
bindgen=${WASM_BINDGEN:-wasm-bindgen}
have=$("$bindgen" --version | awk '{ print $2 }')

if [[ "$have" != "$want" ]]; then
  echo "build-web: $bindgen is $have; Cargo.lock has wasm-bindgen $want" >&2
  exit 1
fi

cargo build "${flags[@]}" --target wasm32-unknown-unknown -p x3d-web

target_dir=$(cargo metadata --format-version 1 --no-deps | python3 -c 'import json, sys; print(json.load(sys.stdin)["target_directory"])')

"$bindgen" --target web --no-typescript --out-dir crates/x3d-web/web/pkg \
  "$target_dir/wasm32-unknown-unknown/$profile/x3d_web.wasm"

# X_ITE's own field classes for the page (X3D.SFVec3f, X3DField, X3DConstants, ...): the generated files of the Script
# prelude (crates/x3d-script/src/prelude, verbatim X_ITE 16.5.0) as one ES module, so the page and the Script engine
# share one implementation. web/x_ite_r.mjs mirrors the field objects of nodes with the engine.
prelude=crates/x3d-script/src/prelude
{
  cat <<'JS'
// Generated by tools/build-web.sh from crates/x3d-script/src/prelude (math.js, fields.js, node_types.js), which
// crates/x3d-script/tools/gen_prelude_xite.py generates from the pinned X_ITE 16.5.0. Do not edit.
//
// X_ITE (https://github.com/create3000/x_ite), MIT, Copyright (c) 2009 Holger Seelig and other contributors.

// What the generated files call. X3DGenerator's number formats are X_ITE's own Intl.NumberFormat; x_ite_r.mjs sets
// fieldCallbackAdded.
const numberFormats = new Map ();

const __bridge =
{
   intlFormat (scientific, precision, value)
   {
      const key = `${scientific}:${precision}`;

      let format = numberFormats .get (key);

      if (!format)
      {
         format = new Intl .NumberFormat ("en",
         {
            notation: scientific ? "scientific" : "standard",
            maximumSignificantDigits: precision,
            useGrouping: false,
         })
         .format;

         numberFormats .set (key, format);
      }

      return format (value);
   },
   fieldCallbackAdded () { },
   withBase () { return globalThis; },
};

JS
  cat "$prelude/math.js" "$prelude/fields.js" "$prelude/node_types.js"
  cat <<'JS'

export {
   __bridge, X3DConstants, X3DObject, X3DChildObject, X3DField, X3DArrayField, X3DFieldDefinition, FieldDefinitionArray,
   SFNodeCache, Fields, NODE_TYPES, X3D_CONSTANTS_CORE, X3D_CONSTANTS_ALL, X3D_COMPONENTS, X3D_COMPONENT_CONSTANTS,
};
JS
} > crates/x3d-web/web/pkg/fields.mjs

ls -l crates/x3d-web/web/pkg
