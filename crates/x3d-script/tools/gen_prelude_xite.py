"""Generate the X_ITE parts of the Script prelude from the pinned X_ITE (oracle/x_ite-pin/src, 16.5.0 @ 34cdf9f97):

  crates/x3d-script/src/prelude/math.js    standard/Math: Algorithm, Vector2/3/4, Color3/4, Matrix2/3/4, Quaternion, Rotation4
  crates/x3d-script/src/prelude/fields.js  the field object model: X3DObject, X3DChildObject, X3DField, the array fields, every
                                           SF and MF class, Events, IterableWeakSet, X3DConstants, the VRML/XML/JSON generators

A Script sees X_ITE's own objects (getValue () hands out a Vector3, a field's prototype chain is X3DObject -> X3DChildObject ->
X3DField -> ...), so the port takes the modules verbatim. Each module becomes a block whose default export is assigned to a name
declared up front with `let` (so import cycles such as SFNode <-> SFNodeCache resolve when the functions run, as with ES module
bindings); `import X from "..."` lines are dropped after checking that X is the name the imported module defines. The places
where X_ITE reaches into its engine (Intl number formatting, the X3DNode a field belongs to, nodes printed into a stream) are
changed by the PATCHES below, each applied to exactly one occurrence of its text; the bridge (prelude/bridge.js) supplies what they
call.

  python3 -I crates/x3d-script/tools/gen_prelude_xite.py          # write both files
  python3 -I crates/x3d-script/tools/gen_prelude_xite.py --check  # exit 1 if one is not up to date
"""
