def with_base(rel, text):
    for prel, name in WITH_BASE:
        if prel != rel:
            continue
        m = list(re.finditer(r"^( *)function " + name + r" \(", text, re.M))
        if len(m) != 1:
            raise SystemExit(f"{rel}: function {name} occurs {len(m)} times")
        indent = m[0].group(1)
        brace = text.index("\n" + indent + "{\n", m[0].end())
        at = brace + len(indent) + 3
        guard = f"{indent}   if (this === undefined) return {name} .apply (__bridge .withBase (), arguments);\n\n"
        text = text[:at] + guard + text[at:]
    return text


IMPORT_DEFAULT = re.compile(r'^import\s+([\w$]+)\s+from\s+"([^"]+)";\s*$')
IMPORT_NAMED = re.compile(r'^import\s+\{\s*([\w\s,]+)\}\s+from\s+"([^"]+)";\s*$')
IMPORT_BARE = re.compile(r'^import\s+"([^"]+)";\s*$')
EXPORT_DEFAULT_NAME = re.compile(r"^export\s+default\s+([\w$]+);\s*$")
EXPORT_DEFAULT_EXPR = re.compile(r'^export\s+default\s+(.+);\s*$')
EXPORT_CONST = re.compile(r'^export\s+const\s+(\w+)\s*=')


def resolve(rel, spec):
    return os.path.normpath(os.path.join(os.path.dirname(rel), spec)).replace(os.sep, "/")


def entry(m):
    if isinstance(m, str):
        return m, None, []
    rel, bind = m[0], m[1]
    return rel, bind, (m[2] if len(m) > 2 else [])


def convert(rel, bind, named, exported_names, defined_files):
    text = open(os.path.join(PIN, rel), encoding="utf-8").read()

    for prel, old, new in PATCHES:
        if prel == rel:
            n = text.count(old)
            if n != 1:
                raise SystemExit(f"{rel}: patch text occurs {n} times:\n{old}")
            text = text.replace(old, new)

    text = with_base(rel, text)

    name = None
    body = []
    exports = []

    for line in text.splitlines():
        m = IMPORT_DEFAULT.match(line)
        if m:
            local, target = m.group(1), resolve(rel, m.group(2))
            if target not in exported_names:
                raise SystemExit(f"{rel}: imports {target}, which is not generated")
            if exported_names[target] != local:
                # Another local name: an alias of a module generated before (a cycle needs the module's own name).
                if target not in defined_files:
                    raise SystemExit(f"{rel}: imports {target} as {local} before it is generated")
                body.append(f"const {local} = {exported_names[target]};")
            continue
        m = IMPORT_NAMED.match(line)
        if m:
            target = resolve(rel, m.group(2))
            for local in [x.strip() for x in m.group(1).split(",") if x.strip()]:
                if local not in named_exports.get(target, []):
                    raise SystemExit(f"{rel}: imports {{{local}}} from {target}, which is not generated")
            continue
        m = IMPORT_BARE.match(line)
        if m:
            target = resolve(rel, m.group(1))
            if target not in defined_files:
                raise SystemExit(f"{rel}: imports {target} for its side effects before it is generated")
            continue
        m = EXPORT_DEFAULT_NAME.match(line)
        if m and (not bind or m.group(1) == bind):
            name = m.group(1)
            continue
        m = EXPORT_DEFAULT_EXPR.match(line)
        if m:
            if not bind:
                raise SystemExit(f"{rel}: `export default <expression>` needs a name")
            name = bind
            body.append(f"const {bind} = {m.group(1)};")
            continue
        if line.startswith("export default ") and bind:
            # A multi-line expression: the rest of the module is its text.
            name = bind
            body.append(f"const {bind} = " + line[len("export default "):])
            continue
        m = EXPORT_CONST.match(line)
        if m:
            exports.append(m.group(1))
            body.append(line[len("export "):])
            continue
        if line.startswith("import ") or line.startswith("export "):
            raise SystemExit(f"{rel}: unsupported module syntax: {line}")
        body.append(line)

    if bind and name is None:
        name = bind
    if name is None and not named:
        raise SystemExit(f"{rel}: no default export")

    indented = "\n".join("   " + l if l.strip() else "" for l in body).rstrip()

    if named:
        missing = [n for n in named if n not in exports]
        if missing:
            raise SystemExit(f"{rel}: does not export {missing}")
        assign = "\n".join(f"   {n}_ = {n};" for n in named)
        return name, f"// {rel}\n{{\n{indented}\n\n{assign}\n}}\n", exports

    return name, f"// {rel}\n{name} = (() =>\n{{\n{indented}\n\n   return {name};\n}})();\n", exports


named_exports = {}


def es_order(modules, known):
    """ES module evaluation order: from each listed module in turn, its imports first (in source order), a module that is
    already being evaluated (a cycle) is skipped, each module after its dependencies."""
    by_rel = {entry(m)[0]: m for m in modules}
    done, active, order = set(known), set(), []

    def visit(rel):
        if rel in done or rel in active:
            return
        active.add(rel)
        for line in open(os.path.join(PIN, rel), encoding="utf-8").read().splitlines():
            m = IMPORT_DEFAULT.match(line) or IMPORT_NAMED.match(line)
            spec = m.group(2) if m else (IMPORT_BARE.match(line).group(1) if IMPORT_BARE.match(line) else None)
            if spec is None:
                continue
            target = resolve(rel, spec)
            if target not in by_rel and target not in known:
                raise SystemExit(f"{rel}: imports {target}, which is not generated")
            if target in by_rel:
                visit(target)
        active.discard(rel)
        done.add(rel)
        order.append(by_rel[rel])

    for m in modules:
        visit(entry(m)[0])
    return order


def generate(modules, known=None, preamble=""):
    """`known`: names an earlier file defines (file -> name); filled with this file's names."""
    exported_names = dict(known or {})
    defined = list(exported_names)
    modules = es_order(modules, exported_names)
    parts = []
    lets = []

    # The names first: every module may refer to any other one at run time.
    for m in modules:
        rel, bind, named = entry(m)
        if named:
            named_exports[rel] = named
            continue
        text = open(os.path.join(PIN, rel), encoding="utf-8").read()
        mm = re.search(r"^export\s+default\s+([\w$]+);\s*$", text, re.M)
        exported_names[rel] = bind or (mm and mm.group(1))
        if not exported_names[rel]:
            raise SystemExit(f"{rel}: no default export name")

    for m in modules:
        rel, bind, named = entry(m)
        name, text, exports = convert(rel, bind, named, exported_names, defined)
        defined.append(rel)
        parts.append(text)
        if named:
            lets.extend(f"{n}_" for n in named)
        else:
            lets.append(name)

    # Named exports are bound under `<name>_` and given their own name after the blocks.
    tail = "".join(f"const {n} = {n}_;\n" for m in modules for n in entry(m)[2])
    if known is not None:
        known.update(exported_names)
    return HEADER + preamble + "\nlet " + ", ".join(lets) + ";\n\n" + "\n".join(parts) + ("\n" + tail if tail else "")


def node_types():
    """oracle/x_ite-node-types.json (oracle/x_ite-node-types.mjs, pinned X_ITE): X3DBaseNode.getType () of every node class as
    X3DConstants names, and X3DConstants once a Core world is loaded and once every component is."""
    import json
    d = json.load(open(os.path.join(ROOT, "oracle", "x_ite-node-types.json"), encoding="utf-8"))
    c = json.load(open(os.path.join(ROOT, "oracle", "x_ite-component-constants.json"), encoding="utf-8"))
    return (HEADER + "//\n// Data: oracle/x_ite-node-types.json, oracle/x_ite-component-constants.json.\n\n"
            + "const NODE_TYPES = " + json.dumps(d["types"], sort_keys=True, separators=(",", ":")) + ";\n\n"
            + "const X3D_CONSTANTS_CORE = " + json.dumps(d["initialConstants"], separators=(",", ":")) + ";\n\n"
            + "const X3D_CONSTANTS_ALL = " + json.dumps(d["constants"], separators=(",", ":")) + ";\n\n"
            + "// The components (name, external, dependencies) and the X3DConstants each external one adds when it loads.\n"
            + "const X3D_COMPONENTS = " + json.dumps([[x["name"], x["external"], x["dependencies"]] for x in c["components"]], separators=(",", ":")) + ";\n\n"
            + "const X3D_COMPONENT_CONSTANTS = " + json.dumps(c["constants"], sort_keys=True, separators=(",", ":")) + ";\n")


def outputs():
    known = {}
    math = generate(MATH, known)
    return {
        os.path.join(OUT_DIR, "math.js"): math,
        os.path.join(OUT_DIR, "fields.js"): generate(FIELDS, known),
        os.path.join(OUT_DIR, "node_types.js"): node_types(),
    }


if __name__ == "__main__":
    out = outputs()
    if sys.argv[1:] == ["--check"]:
        sys.exit(0 if all(os.path.exists(p) and open(p, encoding="utf-8").read() == t for p, t in out.items()) else 1)
    os.makedirs(OUT_DIR, exist_ok=True)
    for p, t in out.items():
        open(p, "w", encoding="utf-8").write(t)
        print(p, len(t))
